-- SCD Type 2 is implemented ONLY for USAGE_TRANSACTIONS, as specified.
-- Other entities are maintained as current-state tables (Type 1/latest row).
USE DATABASE TELECOM_DB;
USE WAREHOUSE TELECOM_WH;

CREATE SCHEMA IF NOT EXISTS SILVER;
CREATE SCHEMA IF NOT EXISTS CONTROL;

-- Monitoring and Recovery:
CREATE TABLE IF NOT EXISTS CONTROL.SILVER_EXCEPTIONS (
    EXCEPTION_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    ENTITY VARCHAR(100),
    BUSINESS_KEY VARCHAR(200),
    EXCEPTION_TYPE VARCHAR(100),
    REASON VARCHAR(2000),
    SOURCE_FILE VARCHAR(1000),
    RAW_RECORD VARIANT,
    DETECTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- Control ledger: one row per successfully handled Bronze source row.
-- Prevents a rerun from reprocessing the same physical Bronze row.
CREATE TABLE IF NOT EXISTS CONTROL.SILVER_PROCESSED_ROWS (
    ENTITY VARCHAR(100),
    BUSINESS_KEY VARCHAR(200),
    SOURCE_FILE VARCHAR(1000),
    BRONZE_LOADED_AT TIMESTAMP_NTZ,
    PROCESSED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT UQ_SILVER_PROCESSED UNIQUE (ENTITY, BUSINESS_KEY, SOURCE_FILE, BRONZE_LOADED_AT)
);

SELECT * FROM CONTROL.SILVER_PROCESSED_ROWS;

-- ---------------------------------------------------------------------------
-- 1. CUSTOMERS
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS SILVER.SILVER_CUSTOMERS (
    CUSTOMER_ID VARCHAR,
    CUSTOMER_NAME VARCHAR,
    CUSTOMER_TYPE VARCHAR,
    DATE_OF_BIRTH DATE,
    EMAIL VARCHAR,
    PHONE VARCHAR,
    ADDRESS_LINE VARCHAR,
    CITY VARCHAR,
    STATE VARCHAR,
    REGION VARCHAR,
    CUSTOMER_SEGMENT VARCHAR,
    REGISTRATION_DATE DATE,
    SOURCE_UPDATED_TS TIMESTAMP_TZ,
    DQ_STATUS VARCHAR,
    SOURCE_FILE VARCHAR,
    PROCESSED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TEMP TABLE TMP_CUSTOMERS AS
SELECT *
FROM (
    SELECT B.*,
           TRY_TO_DATE(B.DATE_OF_BIRTH, 'YYYY-MM-DD') DOB_D,
           TRY_TO_DATE(B.REGISTRATION_DATE, 'YYYY-MM-DD') REG_D,
           TRY_TO_TIMESTAMP_TZ(B.SOURCE_UPDATED_TS) UPDATED_T,
           ROW_NUMBER() OVER (
             PARTITION BY B.CUSTOMER_ID
             ORDER BY TRY_TO_TIMESTAMP_TZ(B.SOURCE_UPDATED_TS) DESC NULLS LAST,
                      B.LOADED_AT DESC
           ) RN
    FROM BRONZE.BRONZE_CUSTOMERS B
    WHERE NULLIF(TRIM(B.CUSTOMER_ID),'') IS NOT NULL
)
WHERE RN=1;

INSERT INTO CONTROL.SILVER_EXCEPTIONS
(ENTITY, BUSINESS_KEY, EXCEPTION_TYPE, REASON, SOURCE_FILE, RAW_RECORD)
SELECT 'CUSTOMERS', CUSTOMER_ID, 'INVALID_DATE',
       'DATE_OF_BIRTH or REGISTRATION_DATE could not be parsed.',
       SOURCE_FILE, OBJECT_CONSTRUCT_KEEP_NULL(*)
FROM TMP_CUSTOMERS
WHERE (NULLIF(TRIM(DATE_OF_BIRTH),'') IS NOT NULL AND DOB_D IS NULL)
   OR (NULLIF(TRIM(REGISTRATION_DATE),'') IS NOT NULL AND REG_D IS NULL)
  AND NOT EXISTS (
    SELECT 1 FROM CONTROL.SILVER_EXCEPTIONS E
    WHERE E.ENTITY='CUSTOMERS' AND E.BUSINESS_KEY=TMP_CUSTOMERS.CUSTOMER_ID
      AND E.EXCEPTION_TYPE='INVALID_DATE' AND E.SOURCE_FILE=TMP_CUSTOMERS.SOURCE_FILE
  );

MERGE INTO SILVER.SILVER_CUSTOMERS T
USING (
  SELECT CUSTOMER_ID, CUSTOMER_NAME, CUSTOMER_TYPE, DOB_D AS DATE_OF_BIRTH,
         EMAIL, PHONE, ADDRESS_LINE, CITY, STATE, REGION, CUSTOMER_SEGMENT,
         REG_D AS REGISTRATION_DATE, UPDATED_T AS SOURCE_UPDATED_TS,
         'IDMC_CLEAN' AS DQ_STATUS,
         SOURCE_FILE
  FROM TMP_CUSTOMERS
  WHERE (NULLIF(TRIM(DATE_OF_BIRTH),'') IS NULL OR DOB_D IS NOT NULL)
    AND (NULLIF(TRIM(REGISTRATION_DATE),'') IS NULL OR REG_D IS NOT NULL)
) S
ON T.CUSTOMER_ID=S.CUSTOMER_ID
WHEN MATCHED AND (
    NVL(T.CUSTOMER_NAME,'')<>NVL(S.CUSTOMER_NAME,'')
 OR NVL(T.CUSTOMER_TYPE,'')<>NVL(S.CUSTOMER_TYPE,'')
 OR NVL(T.EMAIL,'')<>NVL(S.EMAIL,'')
 OR NVL(T.PHONE,'')<>NVL(S.PHONE,'')
 OR NVL(T.ADDRESS_LINE,'')<>NVL(S.ADDRESS_LINE,'')
 OR NVL(T.CITY,'')<>NVL(S.CITY,'')
 OR NVL(T.STATE,'')<>NVL(S.STATE,'')
 OR NVL(T.REGION,'')<>NVL(S.REGION,'')
 OR NVL(T.CUSTOMER_SEGMENT,'')<>NVL(S.CUSTOMER_SEGMENT,'')
 OR NVL(T.SOURCE_UPDATED_TS,'1970-01-01'::TIMESTAMP_TZ) < NVL(S.SOURCE_UPDATED_TS,'1970-01-01'::TIMESTAMP_TZ)
) THEN UPDATE SET
  CUSTOMER_NAME=S.CUSTOMER_NAME, CUSTOMER_TYPE=S.CUSTOMER_TYPE,
  DATE_OF_BIRTH=S.DATE_OF_BIRTH, EMAIL=S.EMAIL, PHONE=S.PHONE,
  ADDRESS_LINE=S.ADDRESS_LINE, CITY=S.CITY, STATE=S.STATE, REGION=S.REGION,
  CUSTOMER_SEGMENT=S.CUSTOMER_SEGMENT, REGISTRATION_DATE=S.REGISTRATION_DATE,
  SOURCE_UPDATED_TS=S.SOURCE_UPDATED_TS, DQ_STATUS=S.DQ_STATUS,
  SOURCE_FILE=S.SOURCE_FILE, PROCESSED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  CUSTOMER_ID,CUSTOMER_NAME,CUSTOMER_TYPE,DATE_OF_BIRTH,EMAIL,PHONE,ADDRESS_LINE,
  CITY,STATE,REGION,CUSTOMER_SEGMENT,REGISTRATION_DATE,SOURCE_UPDATED_TS,
  DQ_STATUS,SOURCE_FILE,PROCESSED_AT
) VALUES (
  S.CUSTOMER_ID,S.CUSTOMER_NAME,S.CUSTOMER_TYPE,S.DATE_OF_BIRTH,S.EMAIL,S.PHONE,
  S.ADDRESS_LINE,S.CITY,S.STATE,S.REGION,S.CUSTOMER_SEGMENT,S.REGISTRATION_DATE,
  S.SOURCE_UPDATED_TS,S.DQ_STATUS,S.SOURCE_FILE,CURRENT_TIMESTAMP()
);

SELECT * FROM SILVER.SILVER_CUSTOMERS;

-- ---------------------------------------------------------------------------
-- 2. NETWORK ELEMENTS
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS SILVER.SILVER_NETWORK_ELEMENTS (
    NETWORK_ELEMENT_ID VARCHAR, ELEMENT_TYPE VARCHAR, PARENT_ELEMENT_ID VARCHAR,
    ELEMENT_NAME VARCHAR, CITY VARCHAR, REGION VARCHAR, LATITUDE NUMBER(10,6),
    LONGITUDE NUMBER(10,6), RATED_CAPACITY NUMBER(18,0), COMMISSIONING_DATE DATE,
    CURRENT_STATUS VARCHAR, SOURCE_UPDATED_TS TIMESTAMP_TZ,
    DQ_STATUS VARCHAR,
    SOURCE_FILE VARCHAR, PROCESSED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TEMP TABLE TMP_NETWORK_ELEMENTS AS
SELECT * FROM (
 SELECT B.*, TRY_TO_DECIMAL(LATITUDE,10,6) LAT_D,
        TRY_TO_DECIMAL(LONGITUDE,10,6) LON_D,
        TRY_TO_DECIMAL(RATED_CAPACITY,18,0) CAP_D,
        TRY_TO_DATE(COMMISSIONING_DATE,'YYYY-MM-DD') COMM_D,
        TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) UPDATED_T,
        ROW_NUMBER() OVER (PARTITION BY NETWORK_ELEMENT_ID
          ORDER BY TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) DESC NULLS LAST, LOADED_AT DESC) RN
 FROM BRONZE.BRONZE_NETWORK_ELEMENTS B
 WHERE NULLIF(TRIM(NETWORK_ELEMENT_ID),'') IS NOT NULL
) WHERE RN=1;

INSERT INTO CONTROL.SILVER_EXCEPTIONS
(ENTITY,BUSINESS_KEY,EXCEPTION_TYPE,REASON,SOURCE_FILE,RAW_RECORD)
SELECT 'NETWORK_ELEMENTS', N.NETWORK_ELEMENT_ID, 'ORPHAN_PARENT',
       'PARENT_ELEMENT_ID does not exist in the current Bronze or Silver network elements.',
       N.SOURCE_FILE, OBJECT_CONSTRUCT_KEEP_NULL(N.*)
FROM TMP_NETWORK_ELEMENTS N
WHERE NULLIF(TRIM(N.PARENT_ELEMENT_ID),'') IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM TMP_NETWORK_ELEMENTS P WHERE P.NETWORK_ELEMENT_ID=N.PARENT_ELEMENT_ID)
  AND NOT EXISTS (SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS P WHERE P.NETWORK_ELEMENT_ID=N.PARENT_ELEMENT_ID)
  AND NOT EXISTS (SELECT 1 FROM CONTROL.SILVER_EXCEPTIONS E WHERE E.ENTITY='NETWORK_ELEMENTS'
    AND E.BUSINESS_KEY=N.NETWORK_ELEMENT_ID AND E.EXCEPTION_TYPE='ORPHAN_PARENT' AND E.SOURCE_FILE=N.SOURCE_FILE);

MERGE INTO SILVER.SILVER_NETWORK_ELEMENTS T
USING (
 SELECT N.NETWORK_ELEMENT_ID,N.ELEMENT_TYPE,N.PARENT_ELEMENT_ID,N.ELEMENT_NAME,N.CITY,N.REGION,
        N.LAT_D LATITUDE,N.LON_D LONGITUDE,N.CAP_D RATED_CAPACITY,N.COMM_D COMMISSIONING_DATE,
        N.CURRENT_STATUS,N.UPDATED_T SOURCE_UPDATED_TS,
        'IDMC_CLEAN' DQ_STATUS,N.SOURCE_FILE
 FROM TMP_NETWORK_ELEMENTS N
 WHERE (NULLIF(TRIM(N.PARENT_ELEMENT_ID),'') IS NULL
    OR EXISTS (SELECT 1 FROM TMP_NETWORK_ELEMENTS P WHERE P.NETWORK_ELEMENT_ID=N.PARENT_ELEMENT_ID)
    OR EXISTS (SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS P WHERE P.NETWORK_ELEMENT_ID=N.PARENT_ELEMENT_ID))
) S
ON T.NETWORK_ELEMENT_ID=S.NETWORK_ELEMENT_ID
WHEN MATCHED AND NVL(T.SOURCE_UPDATED_TS,'1970-01-01'::TIMESTAMP_TZ)<=NVL(S.SOURCE_UPDATED_TS,'1970-01-01'::TIMESTAMP_TZ)
THEN UPDATE SET ELEMENT_TYPE=S.ELEMENT_TYPE,PARENT_ELEMENT_ID=S.PARENT_ELEMENT_ID,
 ELEMENT_NAME=S.ELEMENT_NAME,CITY=S.CITY,REGION=S.REGION,LATITUDE=S.LATITUDE,
 LONGITUDE=S.LONGITUDE,RATED_CAPACITY=S.RATED_CAPACITY,COMMISSIONING_DATE=S.COMMISSIONING_DATE,
 CURRENT_STATUS=S.CURRENT_STATUS,SOURCE_UPDATED_TS=S.SOURCE_UPDATED_TS,DQ_STATUS=S.DQ_STATUS,
 SOURCE_FILE=S.SOURCE_FILE,PROCESSED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT VALUES
(S.NETWORK_ELEMENT_ID,S.ELEMENT_TYPE,S.PARENT_ELEMENT_ID,S.ELEMENT_NAME,S.CITY,S.REGION,
 S.LATITUDE,S.LONGITUDE,S.RATED_CAPACITY,S.COMMISSIONING_DATE,S.CURRENT_STATUS,
 S.SOURCE_UPDATED_TS,S.DQ_STATUS,S.SOURCE_FILE,CURRENT_TIMESTAMP());

SELECT * FROM SILVER.SILVER_NETWORK_ELEMENTS;

-- ---------------------------------------------------------------------------
-- 3. SUBSCRIPTIONS
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS SILVER.SILVER_SUBSCRIPTIONS (
 SUBSCRIPTION_ID VARCHAR,ACCOUNT_ID VARCHAR,CUSTOMER_ID VARCHAR,PLAN_ID VARCHAR,DEVICE_ID VARCHAR,
 SERVICE_TYPE VARCHAR,SERVICE_IDENTIFIER VARCHAR,SUBSCRIPTION_START_DATE DATE,
 SUBSCRIPTION_END_DATE DATE,SUBSCRIPTION_STATUS VARCHAR,CONTRACT_END_DATE DATE,
 SERVICE_REGION VARCHAR,SOURCE_UPDATED_TS TIMESTAMP_TZ,
 DQ_STATUS VARCHAR,SOURCE_FILE VARCHAR,PROCESSED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TEMP TABLE TMP_SUBSCRIPTIONS AS
SELECT * FROM (
 SELECT B.*,TRY_TO_DATE(SUBSCRIPTION_START_DATE,'YYYY-MM-DD') START_D,
        TRY_TO_DATE(SUBSCRIPTION_END_DATE,'YYYY-MM-DD') END_D,
        TRY_TO_DATE(CONTRACT_END_DATE,'YYYY-MM-DD') CONTRACT_D,
        TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) UPDATED_T,
        ROW_NUMBER() OVER (PARTITION BY SUBSCRIPTION_ID
          ORDER BY TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) DESC NULLS LAST,LOADED_AT DESC) RN
 FROM BRONZE.BRONZE_SUBSCRIPTIONS B
 WHERE NULLIF(TRIM(SUBSCRIPTION_ID),'') IS NOT NULL
) WHERE RN=1;

INSERT INTO CONTROL.SILVER_EXCEPTIONS
(ENTITY,BUSINESS_KEY,EXCEPTION_TYPE,REASON,SOURCE_FILE,RAW_RECORD)
SELECT 'SUBSCRIPTIONS',S.SUBSCRIPTION_ID,
       IFF(S.START_D IS NOT NULL AND S.END_D IS NOT NULL AND S.END_D<S.START_D,
           'INVALID_DATE_SEQUENCE','ORPHAN_CUSTOMER'),
       IFF(S.START_D IS NOT NULL AND S.END_D IS NOT NULL AND S.END_D<S.START_D,
           'SUBSCRIPTION_END_DATE is before SUBSCRIPTION_START_DATE.',
           'CUSTOMER_ID does not exist in Silver customers.'),
       S.SOURCE_FILE,OBJECT_CONSTRUCT_KEEP_NULL(S.*)
FROM TMP_SUBSCRIPTIONS S
WHERE (S.START_D IS NOT NULL AND S.END_D IS NOT NULL AND S.END_D<S.START_D)
   OR NOT EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=S.CUSTOMER_ID)
  AND NOT EXISTS (SELECT 1 FROM CONTROL.SILVER_EXCEPTIONS E WHERE E.ENTITY='SUBSCRIPTIONS'
    AND E.BUSINESS_KEY=S.SUBSCRIPTION_ID AND E.SOURCE_FILE=S.SOURCE_FILE
    AND E.EXCEPTION_TYPE IN ('INVALID_DATE_SEQUENCE','ORPHAN_CUSTOMER'));

MERGE INTO SILVER.SILVER_SUBSCRIPTIONS T
USING (
 SELECT S.SUBSCRIPTION_ID,S.ACCOUNT_ID,S.CUSTOMER_ID,S.PLAN_ID,S.DEVICE_ID,S.SERVICE_TYPE,
 S.SERVICE_IDENTIFIER,S.START_D SUBSCRIPTION_START_DATE,S.END_D SUBSCRIPTION_END_DATE,
 S.SUBSCRIPTION_STATUS,S.CONTRACT_D CONTRACT_END_DATE,S.SERVICE_REGION,S.UPDATED_T SOURCE_UPDATED_TS,
 'IDMC_CLEAN' DQ_STATUS,S.SOURCE_FILE
 FROM TMP_SUBSCRIPTIONS S
 WHERE (S.START_D IS NULL OR S.END_D IS NULL OR S.END_D>=S.START_D)
   AND EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=S.CUSTOMER_ID)
) S
ON T.SUBSCRIPTION_ID=S.SUBSCRIPTION_ID
WHEN MATCHED AND NVL(T.SOURCE_UPDATED_TS,'1970-01-01'::TIMESTAMP_TZ)<=NVL(S.SOURCE_UPDATED_TS,'1970-01-01'::TIMESTAMP_TZ)
THEN UPDATE SET ACCOUNT_ID=S.ACCOUNT_ID,CUSTOMER_ID=S.CUSTOMER_ID,PLAN_ID=S.PLAN_ID,
 DEVICE_ID=S.DEVICE_ID,SERVICE_TYPE=S.SERVICE_TYPE,SERVICE_IDENTIFIER=S.SERVICE_IDENTIFIER,
 SUBSCRIPTION_START_DATE=S.SUBSCRIPTION_START_DATE,SUBSCRIPTION_END_DATE=S.SUBSCRIPTION_END_DATE,
 SUBSCRIPTION_STATUS=S.SUBSCRIPTION_STATUS,CONTRACT_END_DATE=S.CONTRACT_END_DATE,
 SERVICE_REGION=S.SERVICE_REGION,SOURCE_UPDATED_TS=S.SOURCE_UPDATED_TS,DQ_STATUS=S.DQ_STATUS,
 SOURCE_FILE=S.SOURCE_FILE,PROCESSED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT VALUES
(S.SUBSCRIPTION_ID,S.ACCOUNT_ID,S.CUSTOMER_ID,S.PLAN_ID,S.DEVICE_ID,S.SERVICE_TYPE,
 S.SERVICE_IDENTIFIER,S.SUBSCRIPTION_START_DATE,S.SUBSCRIPTION_END_DATE,S.SUBSCRIPTION_STATUS,
 S.CONTRACT_END_DATE,S.SERVICE_REGION,S.SOURCE_UPDATED_TS,S.DQ_STATUS,S.SOURCE_FILE,CURRENT_TIMESTAMP());

