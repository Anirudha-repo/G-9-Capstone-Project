CREATE OR REPLACE TEMP TABLE TMP_TICKETS AS
SELECT * FROM (
 SELECT B.*,TRY_TO_TIMESTAMP_TZ(TICKET_CREATE_TS) CREATE_T,
        TRY_TO_TIMESTAMP_TZ(TICKET_RESOLVE_TS) RESOLVE_T,
        TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) UPDATED_T,
        ROW_NUMBER() OVER (PARTITION BY TICKET_ID
          ORDER BY TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) DESC NULLS LAST,LOADED_AT DESC) RN
 FROM BRONZE.BRONZE_TROUBLE_TICKETS B
 WHERE NULLIF(TRIM(TICKET_ID),'') IS NOT NULL
) WHERE RN=1;

INSERT INTO CONTROL.SILVER_EXCEPTIONS
(ENTITY,BUSINESS_KEY,EXCEPTION_TYPE,REASON,SOURCE_FILE,RAW_RECORD)
SELECT 'TROUBLE_TICKETS',T.TICKET_ID,
 CASE WHEN T.CREATE_T IS NOT NULL AND T.RESOLVE_T IS NOT NULL AND T.RESOLVE_T<T.CREATE_T THEN 'INVALID_DATE_SEQUENCE'
      WHEN NOT EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=T.CUSTOMER_ID) THEN 'ORPHAN_CUSTOMER'
      WHEN NULLIF(TRIM(T.SUBSCRIPTION_ID),'') IS NOT NULL AND NOT EXISTS
           (SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S WHERE S.SUBSCRIPTION_ID=T.SUBSCRIPTION_ID) THEN 'ORPHAN_SUBSCRIPTION'
      WHEN NULLIF(TRIM(T.NETWORK_INCIDENT_ID),'') IS NOT NULL AND NOT EXISTS
           (SELECT 1 FROM SILVER.SILVER_NETWORK_INCIDENTS I WHERE I.NETWORK_INCIDENT_ID=T.NETWORK_INCIDENT_ID) THEN 'ORPHAN_INCIDENT'
 END,
 CASE WHEN T.CREATE_T IS NOT NULL AND T.RESOLVE_T IS NOT NULL AND T.RESOLVE_T<T.CREATE_T THEN 'TICKET_RESOLVE_TS is before TICKET_CREATE_TS.'
      WHEN NOT EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=T.CUSTOMER_ID) THEN 'CUSTOMER_ID does not exist.'
      WHEN NULLIF(TRIM(T.SUBSCRIPTION_ID),'') IS NOT NULL AND NOT EXISTS
           (SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S WHERE S.SUBSCRIPTION_ID=T.SUBSCRIPTION_ID) THEN 'SUBSCRIPTION_ID does not exist.'
      WHEN NULLIF(TRIM(T.NETWORK_INCIDENT_ID),'') IS NOT NULL AND NOT EXISTS
           (SELECT 1 FROM SILVER.SILVER_NETWORK_INCIDENTS I WHERE I.NETWORK_INCIDENT_ID=T.NETWORK_INCIDENT_ID) THEN 'NETWORK_INCIDENT_ID does not exist.'
 END,T.SOURCE_FILE,OBJECT_CONSTRUCT_KEEP_NULL(T.*)
FROM TMP_TICKETS T
WHERE (T.CREATE_T IS NOT NULL AND T.RESOLVE_T IS NOT NULL AND T.RESOLVE_T<T.CREATE_T)
 OR NOT EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=T.CUSTOMER_ID)
 OR (NULLIF(TRIM(T.SUBSCRIPTION_ID),'') IS NOT NULL AND NOT EXISTS
     (SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S WHERE S.SUBSCRIPTION_ID=T.SUBSCRIPTION_ID))
 OR (NULLIF(TRIM(T.NETWORK_INCIDENT_ID),'') IS NOT NULL AND NOT EXISTS
     (SELECT 1 FROM SILVER.SILVER_NETWORK_INCIDENTS I WHERE I.NETWORK_INCIDENT_ID=T.NETWORK_INCIDENT_ID));

