-- 4. NETWORK INCIDENTS
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS SILVER.SILVER_NETWORK_INCIDENTS (
 NETWORK_INCIDENT_ID VARCHAR,PRIMARY_ELEMENT_ID VARCHAR,INCIDENT_START_TS TIMESTAMP_TZ,
 INCIDENT_END_TS TIMESTAMP_TZ,INCIDENT_TYPE VARCHAR,SEVERITY VARCHAR,AFFECTED_REGION VARCHAR,
 ROOT_CAUSE VARCHAR,INCIDENT_STATUS VARCHAR,ESTIMATED_CUSTOMERS_IMPACTED NUMBER(18,0),
 SOURCE_UPDATED_TS TIMESTAMP_TZ,DQ_STATUS VARCHAR,
 SOURCE_FILE VARCHAR,PROCESSED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE TEMP TABLE TMP_INCIDENTS AS
SELECT * FROM (
 SELECT B.*,TRY_TO_TIMESTAMP_TZ(INCIDENT_START_TS) START_T,
        TRY_TO_TIMESTAMP_TZ(INCIDENT_END_TS) END_T,
        TRY_TO_DECIMAL(ESTIMATED_CUSTOMERS_IMPACTED,18,0) IMPACT_N,
        TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) UPDATED_T,
        ROW_NUMBER() OVER (PARTITION BY NETWORK_INCIDENT_ID
          ORDER BY TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) DESC NULLS LAST,LOADED_AT DESC) RN
 FROM BRONZE.BRONZE_NETWORK_INCIDENTS B
 WHERE NULLIF(TRIM(NETWORK_INCIDENT_ID),'') IS NOT NULL
) WHERE RN=1;

INSERT INTO CONTROL.SILVER_EXCEPTIONS
(ENTITY,BUSINESS_KEY,EXCEPTION_TYPE,REASON,SOURCE_FILE,RAW_RECORD)
SELECT 'NETWORK_INCIDENTS',I.NETWORK_INCIDENT_ID,
       IFF(I.START_T IS NOT NULL AND I.END_T IS NOT NULL AND I.END_T<I.START_T,
           'INVALID_DATE_SEQUENCE','ORPHAN_NETWORK_ELEMENT'),
       IFF(I.START_T IS NOT NULL AND I.END_T IS NOT NULL AND I.END_T<I.START_T,
           'INCIDENT_END_TS is before INCIDENT_START_TS.',
           'PRIMARY_ELEMENT_ID does not exist in Silver network elements.'),
       I.SOURCE_FILE,OBJECT_CONSTRUCT_KEEP_NULL(I.*)
FROM TMP_INCIDENTS I
WHERE (I.START_T IS NOT NULL AND I.END_T IS NOT NULL AND I.END_T<I.START_T)
   OR NOT EXISTS (SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N WHERE N.NETWORK_ELEMENT_ID=I.PRIMARY_ELEMENT_ID)
  AND NOT EXISTS (SELECT 1 FROM CONTROL.SILVER_EXCEPTIONS E WHERE E.ENTITY='NETWORK_INCIDENTS'
    AND E.BUSINESS_KEY=I.NETWORK_INCIDENT_ID AND E.SOURCE_FILE=I.SOURCE_FILE
    AND E.EXCEPTION_TYPE IN ('INVALID_DATE_SEQUENCE','ORPHAN_NETWORK_ELEMENT'));

MERGE INTO SILVER.SILVER_NETWORK_INCIDENTS T
USING (
 SELECT I.NETWORK_INCIDENT_ID,I.PRIMARY_ELEMENT_ID,I.START_T INCIDENT_START_TS,I.END_T INCIDENT_END_TS,
 I.INCIDENT_TYPE,I.SEVERITY,I.AFFECTED_REGION,I.ROOT_CAUSE,I.INCIDENT_STATUS,I.IMPACT_N ESTIMATED_CUSTOMERS_IMPACTED,
 I.UPDATED_T SOURCE_UPDATED_TS,'IDMC_CLEAN' DQ_STATUS,I.SOURCE_FILE
 FROM TMP_INCIDENTS I
 WHERE (I.START_T IS NULL OR I.END_T IS NULL OR I.END_T>=I.START_T)
 AND EXISTS (SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N WHERE N.NETWORK_ELEMENT_ID=I.PRIMARY_ELEMENT_ID)
) S
ON T.NETWORK_INCIDENT_ID=S.NETWORK_INCIDENT_ID
WHEN MATCHED AND NVL(T.SOURCE_UPDATED_TS,'1970-01-01'::TIMESTAMP_TZ)<=NVL(S.SOURCE_UPDATED_TS,'1970-01-01'::TIMESTAMP_TZ)
THEN UPDATE SET PRIMARY_ELEMENT_ID=S.PRIMARY_ELEMENT_ID,INCIDENT_START_TS=S.INCIDENT_START_TS,
 INCIDENT_END_TS=S.INCIDENT_END_TS,INCIDENT_TYPE=S.INCIDENT_TYPE,SEVERITY=S.SEVERITY,
 AFFECTED_REGION=S.AFFECTED_REGION,ROOT_CAUSE=S.ROOT_CAUSE,INCIDENT_STATUS=S.INCIDENT_STATUS,
 ESTIMATED_CUSTOMERS_IMPACTED=S.ESTIMATED_CUSTOMERS_IMPACTED,SOURCE_UPDATED_TS=S.SOURCE_UPDATED_TS,DQ_STATUS=S.DQ_STATUS,
 SOURCE_FILE=S.SOURCE_FILE,PROCESSED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT VALUES
(S.NETWORK_INCIDENT_ID,S.PRIMARY_ELEMENT_ID,S.INCIDENT_START_TS,S.INCIDENT_END_TS,
 S.INCIDENT_TYPE,S.SEVERITY,S.AFFECTED_REGION,S.ROOT_CAUSE,S.INCIDENT_STATUS,
 S.ESTIMATED_CUSTOMERS_IMPACTED,S.SOURCE_UPDATED_TS,S.DQ_STATUS,S.SOURCE_FILE,CURRENT_TIMESTAMP());

 SELECT * FROM SILVER_NETWORK_ELEMENTS;

-- ---------------------------------------------------------------------------
-- 5. USAGE TRANSACTIONS: SCD TYPE 2 ONLY
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS SILVER.SILVER_USAGE_TRANSACTIONS (
 USAGE_TRANSACTION_ID VARCHAR, SUBSCRIPTION_ID VARCHAR, CUSTOMER_ID VARCHAR,
 USAGE_TS TIMESTAMP_TZ, USAGE_TYPE VARCHAR, VOICE_MINUTES NUMBER(12,2),
 SMS_COUNT NUMBER(12,0), DATA_VOLUME_MB NUMBER(18,2), ROAMING_FLAG BOOLEAN,
 NETWORK_ELEMENT_ID VARCHAR, CHARGE_AMOUNT NUMBER(12,2), SOURCE_UPDATED_TS TIMESTAMP_TZ,
 EFFECTIVE_FROM TIMESTAMP_TZ, EFFECTIVE_TO TIMESTAMP_TZ, IS_CURRENT BOOLEAN,
 DQ_STATUS VARCHAR, SOURCE_FILE VARCHAR,
 PROCESSED_AT TIMESTAMP_NTZ
);


CREATE OR REPLACE TEMP TABLE TMP_USAGE AS
SELECT * FROM (
 SELECT B.*,TRY_TO_TIMESTAMP_TZ(USAGE_TS) USAGE_T,
        TRY_TO_DECIMAL(VOICE_MINUTES,12,2) VOICE_N,
        TRY_TO_DECIMAL(SMS_COUNT,12,0) SMS_N,
        TRY_TO_DECIMAL(DATA_VOLUME_MB,18,2) DATA_N,
        TRY_TO_BOOLEAN(ROAMING_FLAG) ROAMING_B,
        TRY_TO_DECIMAL(CHARGE_AMOUNT,12,2) CHARGE_N,
        TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) UPDATED_T,
        ROW_NUMBER() OVER (PARTITION BY USAGE_TRANSACTION_ID
          ORDER BY TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS) DESC NULLS LAST,LOADED_AT DESC) RN
 FROM BRONZE.BRONZE_USAGE_TRANSACTIONS B
 WHERE NULLIF(TRIM(USAGE_TRANSACTION_ID),'') IS NOT NULL
) WHERE RN=1;

SELECT * FROM CONTROL.SILVER_EXCEPTIONS;
-- Route invalid references and unparseable required timestamps to exceptions.
INSERT INTO CONTROL.SILVER_EXCEPTIONS
(ENTITY,BUSINESS_KEY,EXCEPTION_TYPE,REASON,SOURCE_FILE,RAW_RECORD)
SELECT 'USAGE_TRANSACTIONS',U.USAGE_TRANSACTION_ID,
       CASE WHEN U.USAGE_T IS NULL THEN 'INVALID_USAGE_TIMESTAMP'
            WHEN NOT EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=U.CUSTOMER_ID) THEN 'ORPHAN_CUSTOMER'
            WHEN NOT EXISTS (SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S WHERE S.SUBSCRIPTION_ID=U.SUBSCRIPTION_ID) THEN 'ORPHAN_SUBSCRIPTION'
            WHEN NOT EXISTS (SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N WHERE N.NETWORK_ELEMENT_ID=U.NETWORK_ELEMENT_ID) THEN 'ORPHAN_NETWORK_ELEMENT'
       END,
       CASE WHEN U.USAGE_T IS NULL THEN 'USAGE_TS could not be parsed.'
            WHEN NOT EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=U.CUSTOMER_ID) THEN 'CUSTOMER_ID does not exist.'
            WHEN NOT EXISTS (SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S WHERE S.SUBSCRIPTION_ID=U.SUBSCRIPTION_ID) THEN 'SUBSCRIPTION_ID does not exist.'
            WHEN NOT EXISTS (SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N WHERE N.NETWORK_ELEMENT_ID=U.NETWORK_ELEMENT_ID) THEN 'NETWORK_ELEMENT_ID does not exist.'
       END,
       U.SOURCE_FILE,OBJECT_CONSTRUCT_KEEP_NULL(U.*)
FROM TMP_USAGE U
WHERE U.USAGE_T IS NULL
 OR NOT EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=U.CUSTOMER_ID)
 OR NOT EXISTS (SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S WHERE S.SUBSCRIPTION_ID=U.SUBSCRIPTION_ID)
 OR NOT EXISTS (SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N WHERE N.NETWORK_ELEMENT_ID=U.NETWORK_ELEMENT_ID);


-- The outlier is retained and flagged. Exact audit-derived threshold: 1,000,000 MB.
-- EFFECTIVE_FROM uses SOURCE_UPDATED_TS when present, otherwise Bronze LOADED_AT.
-- Close current version only when a newer version with changed content arrives.
UPDATE SILVER.SILVER_USAGE_TRANSACTIONS T
SET EFFECTIVE_TO = S.VERSION_TS,
    IS_CURRENT = FALSE,
    PROCESSED_AT = CURRENT_TIMESTAMP()
FROM (
 SELECT U.USAGE_TRANSACTION_ID,
        COALESCE(U.UPDATED_T,U.LOADED_AT::TIMESTAMP_TZ) VERSION_TS,
        HASH(U.SUBSCRIPTION_ID,U.CUSTOMER_ID,U.USAGE_T,U.USAGE_TYPE,U.VOICE_N,U.SMS_N,
             U.DATA_N,U.ROAMING_B,U.NETWORK_ELEMENT_ID,U.CHARGE_N) ROW_HASH
 FROM TMP_USAGE U
 WHERE U.USAGE_T IS NOT NULL
   AND EXISTS (SELECT 1 FROM SILVER.SILVER_CUSTOMERS C WHERE C.CUSTOMER_ID=U.CUSTOMER_ID)
