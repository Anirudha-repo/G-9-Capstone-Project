USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS TELECOM_WH
  WAREHOUSE_SIZE = 'XSMALL' 
  AUTO_SUSPEND = 60 
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS TELECOM_DB DATA_RETENTION_TIME_IN_DAYS = 1;

USE DATABASE TELECOM_DB;
USE WAREHOUSE TELECOM_WH;

CREATE SCHEMA IF NOT EXISTS BRONZE      COMMENT = 'Raw IDMC-valid files + load metadata';
CREATE SCHEMA IF NOT EXISTS SILVER      COMMENT = 'Typed, de-duplicated, relationship-validated';
CREATE SCHEMA IF NOT EXISTS GOLD        COMMENT = 'Dimensions, facts, marts';
CREATE SCHEMA IF NOT EXISTS CONSUMPTION COMMENT = 'Secure views, Snowpark score, Streamlit';
CREATE SCHEMA IF NOT EXISTS CONTROL     COMMENT = 'RBAC, masking, audit, quarantine, recovery';

-- Audit and Quarantine Records:
USE SCHEMA CONTROL;

CREATE OR REPLACE FILE FORMAT QUARANTINE_LINE_FF
    TYPE = CSV
    FIELD_DELIMITER = NONE
    RECORD_DELIMITER = '\n'
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = NONE
    TRIM_SPACE = FALSE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

CREATE OR REPLACE STAGE QUARANTINE_STAGE
  FILE_FORMAT = CONTROL.QUARANTINE_LINE_FF
  COMMENT = 'IDMC duplicate/reject/warning files (audit only)';

CREATE OR REPLACE TABLE QUARANTINE_RECORDS (
    QUARANTINE_ID NUMBER AUTOINCREMENT,
    ENTITY VARCHAR(100),
    ROUTE VARCHAR(50),
    RAW_RECORD VARCHAR,
    SOURCE_FILE VARCHAR(500),
    FILE_ROW_NUMBER NUMBER,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

LIST @QUARANTINE_STAGE;

COPY INTO TELECOM_DB.CONTROL.QUARANTINE_RECORDS
(
    ENTITY,
    ROUTE,
    RAW_RECORD,
    SOURCE_FILE,
    FILE_ROW_NUMBER
)
FROM
(
    SELECT
        CASE

            WHEN METADATA$FILENAME ILIKE '%customers_audit.csv%'
                THEN 'CUSTOMERS'

            WHEN METADATA$FILENAME ILIKE '%subscriptions_audit.csv%'
                THEN 'SUBSCRIPTIONS'

            WHEN METADATA$FILENAME ILIKE '%network_elements_audit_dup.csv%'
                THEN 'NETWORK_ELEMENTS'

            WHEN METADATA$FILENAME ILIKE '%usage_transactions_audit_dup.csv%'
                THEN 'USAGE_TRANSACTIONS'

            WHEN METADATA$FILENAME ILIKE '%usage_transactions_audit.csv%'
                THEN 'USAGE_TRANSACTIONS'

            WHEN METADATA$FILENAME ILIKE '%network_incidents_audit.csv%'
                THEN 'NETWORK_INCIDENTS'

            WHEN METADATA$FILENAME ILIKE '%network_events_audit_dup.csv%'
                THEN 'NETWORK_EVENTS'

            WHEN METADATA$FILENAME ILIKE '%network_events_audit.csv%'
                THEN 'NETWORK_EVENTS'

            WHEN METADATA$FILENAME ILIKE '%trouble_tickets_audit.csv%'
                THEN 'TROUBLE_TICKETS'

            ELSE 'UNKNOWN'
        END,
        CASE
            WHEN METADATA$FILENAME ILIKE '%audit_dup%'
                THEN 'DUPLICATE'
            ELSE 'AUDIT'
        END,
        $1,
        METADATA$FILENAME,
        METADATA$FILE_ROW_NUMBER
    FROM @TELECOM_DB.CONTROL.QUARANTINE_STAGE
)
PATTERN = '(?i).*(customers_audit|subscriptions_audit|network_elements_audit_dup|usage_transactions_audit|network_incidents_audit|network_events_audit|trouble_tickets_audit|usage_transactions_audit)[.]csv([.]gz)?$'
ON_ERROR = 'ABORT_STATEMENT';

-- Initial batch. Valid rows = rows you loaded into Bronze (COPY used ABORT_STATEMENT,so Bronze rows = rows in the valid file)
CREATE TABLE IF NOT EXISTS AUDIT_IDMC_MANIFEST (
    BATCH_LABEL VARCHAR(50),
    ENTITY VARCHAR(100),
    SOURCE_FILE_ROWS NUMBER,
    IDMC_VALID_ROWS NUMBER,
    IDMC_DUPLICATE_ROWS NUMBER,
    IDMC_REJECT_ROWS NUMBER,
    IDMC_WARNING_ROWS NUMBER,
    NOTES VARCHAR(1000),
    RECORDED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_AUDIT_IDMC_MANIFEST
        PRIMARY KEY (BATCH_LABEL, ENTITY)
);

MERGE INTO TELECOM_DB.CONTROL.AUDIT_IDMC_MANIFEST T
USING (
    SELECT *
    FROM VALUES
    ('B001','CUSTOMERS',900,895),

    ('B001','SUBSCRIPTIONS',1400,1399),

    ('B001','NETWORK_ELEMENTS',400,399),

    ('B001','USAGE_TRANSACTIONS',2200,2197),

    ('B001','TROUBLE_TICKETS',700,699),

    ('B001','NETWORK_INCIDENTS',400,399),

    ('B001','NETWORK_EVENTS',900,898)
    AS V(BATCH_LABEL,ENTITY,SOURCE_ROWS,VALID_ROWS)
) S
ON T.BATCH_LABEL = S.BATCH_LABEL
AND T.ENTITY = S.ENTITY
WHEN MATCHED THEN UPDATE SET
    T.SOURCE_FILE_ROWS = S.SOURCE_ROWS,
    T.IDMC_VALID_ROWS = S.VALID_ROWS
WHEN NOT MATCHED THEN INSERT
(
    BATCH_LABEL,
    ENTITY,
    SOURCE_FILE_ROWS,
    IDMC_VALID_ROWS,
    IDMC_DUPLICATE_ROWS,
    IDMC_REJECT_ROWS,
    IDMC_WARNING_ROWS,
    NOTES
)
VALUES
(
    S.BATCH_LABEL,
    S.ENTITY,
    S.SOURCE_ROWS,
    S.VALID_ROWS,
    NULL,
    NULL,
    NULL,
    'Initial IDMC batch. Individual quality counts pending reconciliation.'
);

