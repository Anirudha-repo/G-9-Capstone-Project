USE DATABASE TELECOM_DB;

CREATE OR REPLACE FILE FORMAT BRONZE.TELECOM_CSV_FF 
TYPE=CSV 
FIELD_DELIMITER=',' 
SKIP_HEADER=1 
FIELD_OPTIONALLY_ENCLOSED_BY='"' 
TRIM_SPACE=TRUE 
EMPTY_FIELD_AS_NULL=TRUE 
NULL_IF=('NULL','null','');

CREATE OR REPLACE FILE FORMAT BRONZE.TELECOM_JSON_FF 
TYPE=JSON 
STRIP_OUTER_ARRAY=TRUE;

CREATE OR REPLACE STAGE BRONZE.TELECOM_STAGE 
FILE_FORMAT=BRONZE.TELECOM_CSV_FF 
DIRECTORY=(ENABLE=TRUE);
