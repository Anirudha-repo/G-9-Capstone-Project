       (SELECT COUNT(*) FROM BRONZE.BRONZE_CUSTOMERS) BRONZE_ROWS,
       (SELECT COUNT(*) FROM SILVER.SILVER_CUSTOMERS) SILVER_ROWS
UNION ALL SELECT 'SUBSCRIPTIONS',1400,
       (SELECT COUNT(*) FROM BRONZE.BRONZE_SUBSCRIPTIONS),
       (SELECT COUNT(*) FROM SILVER.SILVER_SUBSCRIPTIONS)
UNION ALL SELECT 'NETWORK_ELEMENTS',400,
       (SELECT COUNT(*) FROM BRONZE.BRONZE_NETWORK_ELEMENTS),
       (SELECT COUNT(*) FROM SILVER.SILVER_NETWORK_ELEMENTS)
UNION ALL SELECT 'USAGE_TRANSACTIONS',2200,
       (SELECT COUNT(*) FROM BRONZE.BRONZE_USAGE_TRANSACTIONS),
       (SELECT COUNT(*) FROM SILVER.VW_USAGE_TRANSACTIONS_CURRENT)
UNION ALL SELECT 'TROUBLE_TICKETS',700,
       (SELECT COUNT(*) FROM BRONZE.BRONZE_TROUBLE_TICKETS),
       (SELECT COUNT(*) FROM SILVER.SILVER_TROUBLE_TICKETS)
UNION ALL SELECT 'NETWORK_INCIDENTS',400,
       (SELECT COUNT(*) FROM BRONZE.BRONZE_NETWORK_INCIDENTS),
       (SELECT COUNT(*) FROM SILVER.SILVER_NETWORK_INCIDENTS)
UNION ALL SELECT 'NETWORK_EVENTS',900,
       (SELECT COUNT(*) FROM BRONZE.BRONZE_NETWORK_EVENTS),
       (SELECT COUNT(*) FROM SILVER.SILVER_NETWORK_EVENTS);

-- 2. Source data quality signatures. These are expected project test conditions.
SELECT COUNT_IF(TRY_TO_NUMBER(DATA_VOLUME_MB::VARCHAR)=1000000) USAGE_1M_MB_OUTLIERS
FROM SILVER.VW_USAGE_TRANSACTIONS_CURRENT;

SELECT COUNT_IF(TRY_TO_NUMBER(ESTIMATED_CUSTOMERS_IMPACTED::VARCHAR)=500000) INCIDENT_500K_OUTLIERS
FROM SILVER.SILVER_NETWORK_INCIDENTS;

SELECT COUNT_IF(SUBSCRIPTION_END_DATE < SUBSCRIPTION_START_DATE) INVALID_SUBSCRIPTION_DATE_SEQUENCES
FROM SILVER.SILVER_SUBSCRIPTIONS;

SELECT COUNT_IF(INCIDENT_END_TS < INCIDENT_START_TS) INVALID_INCIDENT_DATE_SEQUENCES
FROM SILVER.SILVER_NETWORK_INCIDENTS;

SELECT COUNT_IF(TICKET_RESOLVE_TS < TICKET_CREATE_TS) INVALID_TICKET_DATE_SEQUENCES
FROM SILVER.SILVER_TROUBLE_TICKETS;

-- 3. Dimension/fact duplicate-key checks. Every duplicate count should be zero.
SELECT 'DIM_CUSTOMER' OBJECT_NAME, COUNT(*) DUPLICATE_KEYS FROM
 (SELECT CUSTOMER_ID FROM GOLD.DIM_CUSTOMER GROUP BY CUSTOMER_ID HAVING COUNT(*)>1)
UNION ALL SELECT 'DIM_SUBSCRIPTION',COUNT(*) FROM
 (SELECT SUBSCRIPTION_ID FROM GOLD.DIM_SUBSCRIPTION GROUP BY SUBSCRIPTION_ID HAVING COUNT(*)>1)
UNION ALL SELECT 'DIM_NETWORK_ELEMENT',COUNT(*) FROM
 (SELECT NETWORK_ELEMENT_ID FROM GOLD.DIM_NETWORK_ELEMENT GROUP BY NETWORK_ELEMENT_ID HAVING COUNT(*)>1)
UNION ALL SELECT 'FACT_USAGE',COUNT(*) FROM
 (SELECT USAGE_TRANSACTION_ID FROM GOLD.FACT_USAGE GROUP BY USAGE_TRANSACTION_ID HAVING COUNT(*)>1)
UNION ALL SELECT 'FACT_NETWORK_INCIDENT',COUNT(*) FROM
 (SELECT NETWORK_INCIDENT_ID FROM GOLD.FACT_NETWORK_INCIDENT GROUP BY NETWORK_INCIDENT_ID HAVING COUNT(*)>1)
UNION ALL SELECT 'FACT_TROUBLE_TICKET',COUNT(*) FROM
 (SELECT TICKET_ID FROM GOLD.FACT_TROUBLE_TICKET GROUP BY TICKET_ID HAVING COUNT(*)>1)
UNION ALL SELECT 'FACT_NETWORK_EVENT',COUNT(*) FROM
 (SELECT EVENT_ID FROM GOLD.FACT_NETWORK_EVENT GROUP BY EVENT_ID HAVING COUNT(*)>1);

-- 4. Referential integrity and date-key coverage.
SELECT 'USAGE_CUSTOMER' CHECK_NAME, COUNT(*) ORPHANS
FROM GOLD.FACT_USAGE F LEFT JOIN GOLD.DIM_CUSTOMER D ON F.CUSTOMER_ID=D.CUSTOMER_ID
WHERE D.CUSTOMER_ID IS NULL
UNION ALL SELECT 'USAGE_SUBSCRIPTION',COUNT(*)
FROM GOLD.FACT_USAGE F LEFT JOIN GOLD.DIM_SUBSCRIPTION D ON F.SUBSCRIPTION_ID=D.SUBSCRIPTION_ID
WHERE D.SUBSCRIPTION_ID IS NULL
UNION ALL SELECT 'USAGE_NETWORK_ELEMENT',COUNT(*)
FROM GOLD.FACT_USAGE F LEFT JOIN GOLD.DIM_NETWORK_ELEMENT D ON F.NETWORK_ELEMENT_ID=D.NETWORK_ELEMENT_ID
WHERE D.NETWORK_ELEMENT_ID IS NULL
UNION ALL SELECT 'INCIDENT_NETWORK_ELEMENT',COUNT(*)
FROM GOLD.FACT_NETWORK_INCIDENT F LEFT JOIN GOLD.DIM_NETWORK_ELEMENT D ON F.NETWORK_ELEMENT_ID=D.NETWORK_ELEMENT_ID
WHERE D.NETWORK_ELEMENT_ID IS NULL
UNION ALL SELECT 'EVENT_NETWORK_ELEMENT',COUNT(*)
FROM GOLD.FACT_NETWORK_EVENT F LEFT JOIN GOLD.DIM_NETWORK_ELEMENT D ON F.NETWORK_ELEMENT_ID=D.NETWORK_ELEMENT_ID
WHERE D.NETWORK_ELEMENT_ID IS NULL;

SELECT 'USAGE' FACT_NAME, COUNT(*) MISSING_DATE_KEYS
FROM GOLD.FACT_USAGE F LEFT JOIN GOLD.DIM_DATE D ON F.DATE_KEY=D.DATE_KEY
WHERE D.DATE_KEY IS NULL
UNION ALL SELECT 'INCIDENTS',COUNT(*) FROM GOLD.FACT_NETWORK_INCIDENT F
LEFT JOIN GOLD.DIM_DATE D ON F.DATE_KEY=D.DATE_KEY WHERE D.DATE_KEY IS NULL
UNION ALL SELECT 'TICKETS',COUNT(*) FROM GOLD.FACT_TROUBLE_TICKET F
LEFT JOIN GOLD.DIM_DATE D ON F.DATE_KEY=D.DATE_KEY WHERE D.DATE_KEY IS NULL
UNION ALL SELECT 'EVENTS',COUNT(*) FROM GOLD.FACT_NETWORK_EVENT F
LEFT JOIN GOLD.DIM_DATE D ON F.DATE_KEY=D.DATE_KEY WHERE D.DATE_KEY IS NULL;

-- 5. SCD Type 2 integrity for Usage.
SELECT COUNT(*) MULTIPLE_CURRENT_VERSIONS
FROM (
 SELECT USAGE_TRANSACTION_ID
 FROM SILVER.SILVER_USAGE_TRANSACTIONS
 WHERE IS_CURRENT=TRUE
 GROUP BY USAGE_TRANSACTION_ID HAVING COUNT(*)>1
);

SELECT COUNT(*) NO_CURRENT_VERSION
FROM (
 SELECT USAGE_TRANSACTION_ID
 FROM SILVER.SILVER_USAGE_TRANSACTIONS
 GROUP BY USAGE_TRANSACTION_ID HAVING COUNT_IF(IS_CURRENT=TRUE)=0
);

SELECT COUNT(*) CURRENT_VIEW_MISMATCH
FROM (
 SELECT USAGE_TRANSACTION_ID FROM SILVER.VW_USAGE_TRANSACTIONS_CURRENT
 EXCEPT
 SELECT USAGE_TRANSACTION_ID FROM SILVER.SILVER_USAGE_TRANSACTIONS WHERE IS_CURRENT=TRUE
);

-- 6. KPI checks.
SELECT COUNT(DISTINCT SUBSCRIPTION_ID) ACTIVE_SUBSCRIPTIONS
FROM GOLD.DIM_SUBSCRIPTION WHERE UPPER(TRIM(SUBSCRIPTION_STATUS))='ACTIVE';

SELECT COUNT(*) USAGE_TRANSACTIONS,
       SUM(VOICE_MINUTES) TOTAL_VOICE_MINUTES,
       SUM(SMS_COUNT) TOTAL_SMS_COUNT,
       SUM(DATA_VOLUME_MB) TOTAL_DATA_MB,
       AVG(DATA_VOLUME_MB) AVG_DATA_MB_PER_TRANSACTION,
       DIV0(SUM(DATA_VOLUME_MB),COUNT(DISTINCT SUBSCRIPTION_ID)) AVG_DATA_MB_PER_SUBSCRIPTION
FROM GOLD.FACT_USAGE;

SELECT COUNT(*) INCIDENT_COUNT,
       AVG(INCIDENT_DURATION_MINUTES) AVG_INCIDENT_DURATION_MINUTES,
       SUM(ESTIMATED_CUSTOMERS_IMPACTED) ESTIMATED_CUSTOMERS_IMPACTED,
       AVG(INCIDENT_DURATION_MINUTES) MTTR_MINUTES
FROM GOLD.FACT_NETWORK_INCIDENT;

SELECT COUNT(*) TICKET_COUNT,
       COUNT_IF(TICKET_RESOLVE_TS IS NULL) OPEN_TICKETS,
       AVG(RESOLUTION_MINUTES) AVG_RESOLUTION_MINUTES,
       COUNT_IF(SLA_MET=TRUE) SLA_MET,
       COUNT_IF(SLA_MET=FALSE) SLA_BREACHED,
       COUNT_IF(SLA_MET IS NULL) SLA_NOT_EVALUATED,
       DIV0(COUNT_IF(SLA_MET=TRUE),COUNT_IF(SLA_MET IS NOT NULL))*100 SLA_COMPLIANCE_PCT
FROM GOLD.FACT_TROUBLE_TICKET;

SELECT COUNT_IF(UPPER(TRIM(SEVERITY))='CRITICAL'
                AND UPPER(TRIM(EVENT_STATUS)) NOT IN ('CLEARED','CLOSED','RESOLVED'))
       OPEN_CRITICAL_ALARMS
FROM GOLD.FACT_NETWORK_EVENT;

-- 7. Snowpark output validation:
SELECT COUNT(*) SCORE_ROWS,
       COUNT(DISTINCT NETWORK_ELEMENT_ID) DISTINCT_ELEMENTS,
       COUNT_IF(NETWORK_RISK_SCORE<0 OR NETWORK_RISK_SCORE>100) OUT_OF_RANGE_SCORES,
       COUNT_IF(RISK_CATEGORY NOT IN ('LOW','MEDIUM','HIGH')) INVALID_CATEGORIES,
       COUNT_IF(SCORED_AT IS NULL) NULL_SCORE_TIMESTAMPS
FROM CONSUMPTION.NETWORK_RISK_SNOWPARK;

SELECT RISK_CATEGORY, COUNT(*) ELEMENT_COUNT,
       MIN(NETWORK_RISK_SCORE) MIN_SCORE, MAX(NETWORK_RISK_SCORE) MAX_SCORE
FROM CONSUMPTION.NETWORK_RISK_SNOWPARK
GROUP BY RISK_CATEGORY ORDER BY RISK_CATEGORY;

-- Recomputing one sample score independently from its component scores.
SELECT NETWORK_ELEMENT_ID, NETWORK_RISK_SCORE,
       LEAST(INCIDENT_SCORE+OPEN_ALARM_SCORE+PACKET_LOSS_SCORE+
             LATENCY_SCORE+CUSTOMER_IMPACT_SCORE,100) RECOMPUTED_SCORE,
       RISK_CATEGORY
FROM CONSUMPTION.NETWORK_RISK_SNOWPARK
QUALIFY ROW_NUMBER() OVER (ORDER BY NETWORK_RISK_SCORE DESC)=1;

