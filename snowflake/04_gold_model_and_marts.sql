-- PROJECT 9 TELECOM: GOLD INITIAL BUILD + VALIDATION
-- Run after all seven Silver tables exist and the Usage SCD2 current view is valid.
-- This is a full initial rebuild of Gold. It is NOT the later Stream/Task job.
-- Gold facts use the current Usage version only. Marts are views and update
-- automatically when their underlying Gold facts change.
-- Review/test in a non-production schema first. SQL has not been executed in
-- your Snowflake account, so account-specific execution cannot be guaranteed.

USE DATABASE TELECOM_DB;
USE WAREHOUSE TELECOM_WH;
CREATE SCHEMA IF NOT EXISTS GOLD;

-- 0. Current Usage view. Exactly one current version per transaction is expected.
CREATE OR REPLACE VIEW SILVER.VW_USAGE_TRANSACTIONS_CURRENT AS
SELECT *
FROM SILVER.SILVER_USAGE_TRANSACTIONS
WHERE IS_CURRENT = TRUE;

-- 1. DIMENSIONS (4)
CREATE OR REPLACE TABLE GOLD.DIM_CUSTOMER AS
SELECT CUSTOMER_ID, CUSTOMER_NAME, CUSTOMER_TYPE, DATE_OF_BIRTH, EMAIL, PHONE,
       ADDRESS_LINE, CITY, STATE, REGION, CUSTOMER_SEGMENT, REGISTRATION_DATE
FROM SILVER.SILVER_CUSTOMERS
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY CUSTOMER_ID
  ORDER BY SOURCE_UPDATED_TS DESC NULLS LAST, PROCESSED_AT DESC NULLS LAST
)=1;

CREATE OR REPLACE TABLE GOLD.DIM_SUBSCRIPTION AS
SELECT SUBSCRIPTION_ID, ACCOUNT_ID, CUSTOMER_ID, PLAN_ID, DEVICE_ID, SERVICE_TYPE,
       SERVICE_IDENTIFIER, SUBSCRIPTION_START_DATE, SUBSCRIPTION_END_DATE,
       SUBSCRIPTION_STATUS, CONTRACT_END_DATE, SERVICE_REGION
FROM SILVER.SILVER_SUBSCRIPTIONS
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY SUBSCRIPTION_ID
  ORDER BY SOURCE_UPDATED_TS DESC NULLS LAST, PROCESSED_AT DESC NULLS LAST
)=1;

CREATE OR REPLACE TABLE GOLD.DIM_NETWORK_ELEMENT AS
SELECT NETWORK_ELEMENT_ID, ELEMENT_TYPE, PARENT_ELEMENT_ID, ELEMENT_NAME, CITY,
       REGION, LATITUDE, LONGITUDE, RATED_CAPACITY, COMMISSIONING_DATE, CURRENT_STATUS
FROM SILVER.SILVER_NETWORK_ELEMENTS
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY NETWORK_ELEMENT_ID
  ORDER BY SOURCE_UPDATED_TS DESC NULLS LAST, PROCESSED_AT DESC NULLS LAST
)=1;

-- Date dimension spans the actual date range in the Silver facts.
-- Generator supports a maximum span of 20,000 days (~54 years).
CREATE OR REPLACE TABLE GOLD.DIM_DATE AS
WITH DATES AS (
  SELECT USAGE_TS::DATE D FROM SILVER.VW_USAGE_TRANSACTIONS_CURRENT WHERE USAGE_TS IS NOT NULL
  UNION ALL
  SELECT INCIDENT_START_TS::DATE FROM SILVER.SILVER_NETWORK_INCIDENTS WHERE INCIDENT_START_TS IS NOT NULL
  UNION ALL
  SELECT TICKET_CREATE_TS::DATE FROM SILVER.SILVER_TROUBLE_TICKETS WHERE TICKET_CREATE_TS IS NOT NULL
  UNION ALL
  SELECT EVENT_TIMESTAMP::DATE FROM SILVER.SILVER_NETWORK_EVENTS WHERE EVENT_TIMESTAMP IS NOT NULL
), B AS (
  SELECT COALESCE(MIN(D),'2020-01-01'::DATE) MIN_D,
         COALESCE(MAX(D),'2020-01-01'::DATE) MAX_D FROM DATES
), SERIES AS (
  SELECT DATEADD(DAY,SEQ4(),MIN_D)::DATE FULL_DATE, MAX_D
  FROM B, TABLE(GENERATOR(ROWCOUNT=>20000))
)
SELECT TO_NUMBER(TO_CHAR(FULL_DATE,'YYYYMMDD')) DATE_KEY,
       FULL_DATE, YEAR(FULL_DATE) YEAR, QUARTER(FULL_DATE) QUARTER,
       MONTH(FULL_DATE) MONTH, MONTHNAME(FULL_DATE) MONTH_NAME,
       DAY(FULL_DATE) DAY_OF_MONTH, DAYOFWEEKISO(FULL_DATE) DAY_OF_WEEK_ISO,
       WEEKOFYEAR(FULL_DATE) WEEK_OF_YEAR,
       IFF(DAYOFWEEKISO(FULL_DATE) IN (6,7),TRUE,FALSE) IS_WEEKEND
FROM SERIES
WHERE FULL_DATE<=MAX_D;

-- 2. FACT TABLES (4). Inner joins enforce required dimension relationships.
-- Usage uses only current SCD2 rows and checks subscription/customer agreement.
CREATE OR REPLACE TABLE GOLD.FACT_USAGE AS
SELECT U.USAGE_TRANSACTION_ID, U.SUBSCRIPTION_ID, U.CUSTOMER_ID,
       U.NETWORK_ELEMENT_ID,
       TO_NUMBER(TO_CHAR(U.USAGE_TS::DATE,'YYYYMMDD')) DATE_KEY,
       U.USAGE_TS, U.USAGE_TYPE, U.VOICE_MINUTES, U.SMS_COUNT,
       U.DATA_VOLUME_MB, U.ROAMING_FLAG, U.CHARGE_AMOUNT, U.DQ_STATUS,
       U.EFFECTIVE_FROM USAGE_VERSION_EFFECTIVE_FROM
FROM SILVER.VW_USAGE_TRANSACTIONS_CURRENT U
JOIN GOLD.DIM_SUBSCRIPTION S
  ON U.SUBSCRIPTION_ID=S.SUBSCRIPTION_ID AND U.CUSTOMER_ID=S.CUSTOMER_ID
JOIN GOLD.DIM_CUSTOMER C ON U.CUSTOMER_ID=C.CUSTOMER_ID
JOIN GOLD.DIM_NETWORK_ELEMENT N ON U.NETWORK_ELEMENT_ID=N.NETWORK_ELEMENT_ID
JOIN GOLD.DIM_DATE D
  ON TO_NUMBER(TO_CHAR(U.USAGE_TS::DATE,'YYYYMMDD'))=D.DATE_KEY
WHERE U.USAGE_TS IS NOT NULL;

CREATE OR REPLACE TABLE GOLD.FACT_NETWORK_INCIDENT AS
SELECT I.NETWORK_INCIDENT_ID, I.PRIMARY_ELEMENT_ID NETWORK_ELEMENT_ID,
       TO_NUMBER(TO_CHAR(I.INCIDENT_START_TS::DATE,'YYYYMMDD')) DATE_KEY,
       I.INCIDENT_START_TS, I.INCIDENT_END_TS, I.INCIDENT_TYPE, I.SEVERITY,
       I.AFFECTED_REGION, I.ROOT_CAUSE, I.INCIDENT_STATUS,
       I.ESTIMATED_CUSTOMERS_IMPACTED,
       CASE WHEN I.INCIDENT_END_TS>=I.INCIDENT_START_TS
            THEN DATEDIFF(MINUTE,I.INCIDENT_START_TS,I.INCIDENT_END_TS)
            ELSE NULL END INCIDENT_DURATION_MINUTES,
       I.DQ_STATUS
FROM SILVER.SILVER_NETWORK_INCIDENTS I
JOIN GOLD.DIM_NETWORK_ELEMENT N ON I.PRIMARY_ELEMENT_ID=N.NETWORK_ELEMENT_ID
JOIN GOLD.DIM_DATE D
  ON TO_NUMBER(TO_CHAR(I.INCIDENT_START_TS::DATE,'YYYYMMDD'))=D.DATE_KEY
WHERE I.INCIDENT_START_TS IS NOT NULL;

CREATE OR REPLACE TABLE GOLD.FACT_TROUBLE_TICKET AS
SELECT T.TICKET_ID, T.CUSTOMER_ID, T.SUBSCRIPTION_ID, T.NETWORK_INCIDENT_ID,
       TO_NUMBER(TO_CHAR(T.TICKET_CREATE_TS::DATE,'YYYYMMDD')) DATE_KEY,
       T.TICKET_CREATE_TS, T.TICKET_RESOLVE_TS, T.TICKET_CATEGORY,
       T.PRIORITY_CODE, T.TICKET_STATUS, T.ROOT_CAUSE, T.SLA_TARGET_MINUTES,
       T.ASSIGNED_TEAM,
       CASE WHEN T.TICKET_RESOLVE_TS>=T.TICKET_CREATE_TS
            THEN DATEDIFF(MINUTE,T.TICKET_CREATE_TS,T.TICKET_RESOLVE_TS)
            ELSE NULL END RESOLUTION_MINUTES,
       CASE WHEN T.TICKET_RESOLVE_TS IS NULL OR T.TICKET_RESOLVE_TS<T.TICKET_CREATE_TS
                  OR T.SLA_TARGET_MINUTES IS NULL THEN NULL
            ELSE IFF(DATEDIFF(MINUTE,T.TICKET_CREATE_TS,T.TICKET_RESOLVE_TS)
                     <=T.SLA_TARGET_MINUTES,TRUE,FALSE) END SLA_MET,
       T.DQ_STATUS
FROM SILVER.SILVER_TROUBLE_TICKETS T
JOIN GOLD.DIM_CUSTOMER C ON T.CUSTOMER_ID=C.CUSTOMER_ID
LEFT JOIN GOLD.DIM_SUBSCRIPTION S
  ON T.SUBSCRIPTION_ID=S.SUBSCRIPTION_ID AND T.CUSTOMER_ID=S.CUSTOMER_ID
LEFT JOIN GOLD.DIM_DATE D
  ON TO_NUMBER(TO_CHAR(T.TICKET_CREATE_TS::DATE,'YYYYMMDD'))=D.DATE_KEY
WHERE T.TICKET_CREATE_TS IS NOT NULL;

CREATE OR REPLACE TABLE GOLD.FACT_NETWORK_EVENT AS
SELECT E.EVENT_ID, E.NETWORK_ELEMENT_ID,
       TO_NUMBER(TO_CHAR(E.EVENT_TIMESTAMP::DATE,'YYYYMMDD')) DATE_KEY,
       E.EVENT_TIMESTAMP, E.EVENT_TYPE, E.SEVERITY, E.CPU_UTILIZATION_PCT,
       E.TRAFFIC_UTILIZATION_PCT, E.PACKET_LOSS_PCT, E.LATENCY_MS, E.ALARM_CODE,
       E.ALARM_ACKNOWLEDGED, E.AFFECTED_SERVICES, E.RELATED_ELEMENTS,
       E.REGION, E.CITY, E.EVENT_STATUS, E.SOURCE_SYSTEM, E.DQ_STATUS
FROM SILVER.SILVER_NETWORK_EVENTS E
JOIN GOLD.DIM_NETWORK_ELEMENT N ON E.NETWORK_ELEMENT_ID=N.NETWORK_ELEMENT_ID
JOIN GOLD.DIM_DATE D
  ON TO_NUMBER(TO_CHAR(E.EVENT_TIMESTAMP::DATE,'YYYYMMDD'))=D.DATE_KEY
WHERE E.EVENT_TIMESTAMP IS NOT NULL;

-- 3. BUSINESS MARTS (4). Views recalculate when facts change.
CREATE OR REPLACE VIEW GOLD.MART_USAGE_SUMMARY AS
SELECT USAGE_TS::DATE USAGE_DATE, USAGE_TYPE, ROAMING_FLAG,
       COUNT(*) TRANSACTION_COUNT,
       COUNT(DISTINCT SUBSCRIPTION_ID) SUBSCRIPTIONS_WITH_USAGE,
       SUM(VOICE_MINUTES) TOTAL_VOICE_MINUTES, SUM(SMS_COUNT) TOTAL_SMS_COUNT,
       SUM(DATA_VOLUME_MB) TOTAL_DATA_MB, AVG(DATA_VOLUME_MB) AVG_DATA_MB_PER_TRANSACTION,
       SUM(CHARGE_AMOUNT) TOTAL_CHARGES
FROM GOLD.FACT_USAGE
GROUP BY 1,2,3;

CREATE OR REPLACE VIEW GOLD.MART_NETWORK_RELIABILITY AS
WITH IA AS (
  SELECT NETWORK_ELEMENT_ID, COUNT(*) INCIDENT_COUNT,
         AVG(INCIDENT_DURATION_MINUTES) AVG_INCIDENT_DURATION_MINUTES,
         SUM(COALESCE(ESTIMATED_CUSTOMERS_IMPACTED,0)) ESTIMATED_CUSTOMERS_IMPACTED,
         COUNT_IF(UPPER(COALESCE(SEVERITY,''))='CRITICAL') CRITICAL_INCIDENT_COUNT
  FROM GOLD.FACT_NETWORK_INCIDENT GROUP BY NETWORK_ELEMENT_ID
), EA AS (
  SELECT NETWORK_ELEMENT_ID, COUNT(*) EVENT_COUNT,
         COUNT_IF(UPPER(COALESCE(SEVERITY,''))='CRITICAL'
           AND UPPER(COALESCE(EVENT_STATUS,'')) NOT IN ('CLEARED','CLOSED','RESOLVED'))
           OPEN_CRITICAL_ALARMS,
         AVG(PACKET_LOSS_PCT) AVG_PACKET_LOSS_PCT,
         AVG(LATENCY_MS) AVG_LATENCY_MS,
         MAX(CPU_UTILIZATION_PCT) MAX_CPU_UTILIZATION_PCT,
         MAX(TRAFFIC_UTILIZATION_PCT) MAX_TRAFFIC_UTILIZATION_PCT
  FROM GOLD.FACT_NETWORK_EVENT GROUP BY NETWORK_ELEMENT_ID
)
SELECT N.NETWORK_ELEMENT_ID, N.ELEMENT_NAME, N.ELEMENT_TYPE, N.REGION, N.CITY,
       N.CURRENT_STATUS, COALESCE(I.INCIDENT_COUNT,0) INCIDENT_COUNT,
       I.AVG_INCIDENT_DURATION_MINUTES,
       COALESCE(I.ESTIMATED_CUSTOMERS_IMPACTED,0) ESTIMATED_CUSTOMERS_IMPACTED,
       COALESCE(I.CRITICAL_INCIDENT_COUNT,0) CRITICAL_INCIDENT_COUNT,
       COALESCE(E.EVENT_COUNT,0) EVENT_COUNT,
       COALESCE(E.OPEN_CRITICAL_ALARMS,0) OPEN_CRITICAL_ALARMS,
       E.AVG_PACKET_LOSS_PCT, E.AVG_LATENCY_MS,
       E.MAX_CPU_UTILIZATION_PCT, E.MAX_TRAFFIC_UTILIZATION_PCT
FROM GOLD.DIM_NETWORK_ELEMENT N
LEFT JOIN IA I ON N.NETWORK_ELEMENT_ID=I.NETWORK_ELEMENT_ID
LEFT JOIN EA E ON N.NETWORK_ELEMENT_ID=E.NETWORK_ELEMENT_ID;

CREATE OR REPLACE VIEW GOLD.MART_TICKET_SLA AS
SELECT TICKET_CATEGORY, PRIORITY_CODE, TICKET_STATUS, ASSIGNED_TEAM,
       COUNT(*) TICKET_COUNT,
       COUNT_IF(TICKET_RESOLVE_TS IS NOT NULL) RESOLVED_COUNT,
       COUNT_IF(TICKET_RESOLVE_TS IS NULL) OPEN_COUNT,
       AVG(IFF(TICKET_RESOLVE_TS IS NOT NULL,RESOLUTION_MINUTES,NULL)) AVG_RESOLUTION_MINUTES,
       COUNT_IF(SLA_MET=TRUE) SLA_MET_COUNT,
       COUNT_IF(SLA_MET=FALSE) SLA_BREACHED_COUNT,
       DIV0(COUNT_IF(SLA_MET=TRUE),COUNT_IF(SLA_MET IS NOT NULL))*100 SLA_COMPLIANCE_PCT
FROM GOLD.FACT_TROUBLE_TICKET
GROUP BY 1,2,3,4;

-- Transparent SQL risk score (0-100). The roadmap calls for Snowpark scoring;
-- this view supplies a documented baseline/formula and output structure.
CREATE OR REPLACE VIEW GOLD.MART_NETWORK_RISK AS
WITH X AS (
 SELECT R.*,
   LEAST(COALESCE(INCIDENT_COUNT,0)*5,25) INCIDENT_SCORE,
   LEAST(COALESCE(OPEN_CRITICAL_ALARMS,0)*10,30) OPEN_ALARM_SCORE,
   CASE WHEN AVG_PACKET_LOSS_PCT>=10 THEN 20 WHEN AVG_PACKET_LOSS_PCT>=5 THEN 15
        WHEN AVG_PACKET_LOSS_PCT>=2 THEN 10 WHEN AVG_PACKET_LOSS_PCT>0 THEN 5 ELSE 0 END PACKET_LOSS_SCORE,
   CASE WHEN AVG_LATENCY_MS>=1000 THEN 15 WHEN AVG_LATENCY_MS>=500 THEN 10
        WHEN AVG_LATENCY_MS>=200 THEN 5 ELSE 0 END LATENCY_SCORE,
   CASE WHEN ESTIMATED_CUSTOMERS_IMPACTED>=10000 THEN 10
        WHEN ESTIMATED_CUSTOMERS_IMPACTED>=5000 THEN 7
        WHEN ESTIMATED_CUSTOMERS_IMPACTED>=1000 THEN 4
        WHEN ESTIMATED_CUSTOMERS_IMPACTED>0 THEN 2 ELSE 0 END CUSTOMER_IMPACT_SCORE
 FROM GOLD.MART_NETWORK_RELIABILITY R
), S AS (
 SELECT *, LEAST(INCIDENT_SCORE+OPEN_ALARM_SCORE+PACKET_LOSS_SCORE+
                 LATENCY_SCORE+CUSTOMER_IMPACT_SCORE,100) NETWORK_RISK_SCORE
 FROM X
)
SELECT NETWORK_ELEMENT_ID, ELEMENT_NAME, REGION, CITY, INCIDENT_COUNT,
       CRITICAL_INCIDENT_COUNT, OPEN_CRITICAL_ALARMS, AVG_PACKET_LOSS_PCT,
       AVG_LATENCY_MS, MAX_CPU_UTILIZATION_PCT, MAX_TRAFFIC_UTILIZATION_PCT,
       ESTIMATED_CUSTOMERS_IMPACTED, INCIDENT_SCORE, OPEN_ALARM_SCORE,
       PACKET_LOSS_SCORE, LATENCY_SCORE, CUSTOMER_IMPACT_SCORE, NETWORK_RISK_SCORE,
       CASE WHEN NETWORK_RISK_SCORE>=65 THEN 'HIGH'
            WHEN NETWORK_RISK_SCORE>=35 THEN 'MEDIUM' ELSE 'LOW' END RISK_CATEGORY,
       CURRENT_TIMESTAMP() SCORE_INPUT_REFRESHED_AT
FROM S;

-- 4. EVENT-INCIDENT-SERVICE-TICKET CORRELATION VIEW.
-- Event is correlated to incident on same/related element and event time from
-- 30 minutes before incident start through incident end (or now if open).
-- Tickets link by incident ID; service identifiers/types are matched against
-- the flattened/text affected_services field. Validate actual encoding.
CREATE OR REPLACE VIEW GOLD.VW_EVENT_INCIDENT_CORRELATION AS
SELECT E.EVENT_ID, E.NETWORK_ELEMENT_ID EVENT_NETWORK_ELEMENT_ID,
       E.EVENT_TIMESTAMP, E.EVENT_TYPE, E.SEVERITY EVENT_SEVERITY,
       E.EVENT_STATUS, E.AFFECTED_SERVICES, E.RELATED_ELEMENTS,
       I.NETWORK_INCIDENT_ID, I.NETWORK_ELEMENT_ID INCIDENT_NETWORK_ELEMENT_ID,
       I.INCIDENT_START_TS, I.INCIDENT_END_TS, I.INCIDENT_TYPE,
       I.SEVERITY INCIDENT_SEVERITY, I.INCIDENT_STATUS,
       I.ESTIMATED_CUSTOMERS_IMPACTED, T.TICKET_ID,
       T.CUSTOMER_ID TICKET_CUSTOMER_ID, T.SUBSCRIPTION_ID TICKET_SUBSCRIPTION_ID,
       T.TICKET_STATUS, T.PRIORITY_CODE, S.SUBSCRIPTION_ID CORRELATED_SUBSCRIPTION_ID,
       S.CUSTOMER_ID CORRELATED_CUSTOMER_ID, S.SERVICE_TYPE, S.SERVICE_IDENTIFIER,
       IFF(E.NETWORK_ELEMENT_ID=I.NETWORK_ELEMENT_ID,'SAME_ELEMENT','RELATED_ELEMENT')
         CORRELATION_REASON
FROM GOLD.FACT_NETWORK_EVENT E
JOIN GOLD.FACT_NETWORK_INCIDENT I
  ON (E.NETWORK_ELEMENT_ID=I.NETWORK_ELEMENT_ID OR
      REGEXP_LIKE(COALESCE(E.RELATED_ELEMENTS,''),
        '(^|[^A-Za-z0-9_])'||I.NETWORK_ELEMENT_ID||'([^A-Za-z0-9_]|$)'))
 AND E.EVENT_TIMESTAMP>=DATEADD(MINUTE,-30,I.INCIDENT_START_TS)
 AND E.EVENT_TIMESTAMP<=COALESCE(I.INCIDENT_END_TS,CURRENT_TIMESTAMP())
LEFT JOIN GOLD.FACT_TROUBLE_TICKET T
  ON I.NETWORK_INCIDENT_ID=T.NETWORK_INCIDENT_ID
LEFT JOIN GOLD.DIM_SUBSCRIPTION S
  ON ( (NULLIF(TRIM(S.SERVICE_IDENTIFIER),'') IS NOT NULL AND
        REGEXP_LIKE(UPPER(COALESCE(E.AFFECTED_SERVICES,'')),
          '(^|[^A-Z0-9])'||UPPER(S.SERVICE_IDENTIFIER)||'([^A-Z0-9]|$)'))
       OR (NULLIF(TRIM(S.SERVICE_TYPE),'') IS NOT NULL AND
        POSITION(UPPER(S.SERVICE_TYPE) IN UPPER(COALESCE(E.AFFECTED_SERVICES,'')))>0) );

