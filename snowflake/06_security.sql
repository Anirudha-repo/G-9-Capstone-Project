USE DATABASE TELECOM_DB;

SELECT CURRENT_USER(), CURRENT_ROLE();
USE ROLE SECURITYADMIN;

-- Running role creation/grants as SECURITYADMIN or ACCOUNTADMIN.
CREATE ROLE IF NOT EXISTS NETWORK_ENGINEER_ROLE;
CREATE ROLE IF NOT EXISTS SERVICE_ASSURANCE_ROLE;
CREATE ROLE IF NOT EXISTS TELECOM_MANAGER_ROLE;

GRANT USAGE ON WAREHOUSE TELECOM_WH TO ROLE NETWORK_ENGINEER_ROLE;
GRANT USAGE ON WAREHOUSE TELECOM_WH TO ROLE SERVICE_ASSURANCE_ROLE;
GRANT USAGE ON WAREHOUSE TELECOM_WH TO ROLE TELECOM_MANAGER_ROLE;

GRANT USAGE ON DATABASE TELECOM_DB TO ROLE NETWORK_ENGINEER_ROLE;
GRANT USAGE ON DATABASE TELECOM_DB TO ROLE SERVICE_ASSURANCE_ROLE;
GRANT USAGE ON DATABASE TELECOM_DB TO ROLE TELECOM_MANAGER_ROLE;

-- Engineering can access Bronze and Silver. It does not receive Gold access.
GRANT USAGE ON SCHEMA TELECOM_DB.BRONZE TO ROLE NETWORK_ENGINEER_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA TELECOM_DB.BRONZE TO ROLE NETWORK_ENGINEER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELECOM_DB.BRONZE TO ROLE NETWORK_ENGINEER_ROLE;

GRANT USAGE ON SCHEMA TELECOM_DB.SILVER TO ROLE NETWORK_ENGINEER_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA TELECOM_DB.SILVER TO ROLE NETWORK_ENGINEER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELECOM_DB.SILVER TO ROLE NETWORK_ENGINEER_ROLE;

-- Assurance can inspect Gold and consume secure views.
GRANT USAGE ON SCHEMA TELECOM_DB.GOLD TO ROLE SERVICE_ASSURANCE_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA TELECOM_DB.GOLD TO ROLE SERVICE_ASSURANCE_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELECOM_DB.GOLD TO ROLE SERVICE_ASSURANCE_ROLE;

GRANT USAGE ON SCHEMA TELECOM_DB.CONSUMPTION TO ROLE SERVICE_ASSURANCE_ROLE;
GRANT USAGE ON SCHEMA TELECOM_DB.CONSUMPTION TO ROLE TELECOM_MANAGER_ROLE;

GRANT SELECT ON ALL VIEWS IN SCHEMA TELECOM_DB.CONSUMPTION TO ROLE SERVICE_ASSURANCE_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA TELECOM_DB.CONSUMPTION TO ROLE TELECOM_MANAGER_ROLE;

GRANT SELECT ON FUTURE VIEWS IN SCHEMA TELECOM_DB.CONSUMPTION TO ROLE SERVICE_ASSURANCE_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA TELECOM_DB.CONSUMPTION TO ROLE TELECOM_MANAGER_ROLE;

-- Making Policies
CREATE OR REPLACE MASKING POLICY CONTROL.MASK_CONTACT AS (VAL VARCHAR) 
RETURNS VARCHAR ->
 CASE 
 WHEN CURRENT_ROLE() IN ('NETWORK_ENGINEER_ROLE','ACCOUNTADMIN','SYSADMIN') 
 THEN VAL ELSE '***MASKED***' END;

 SHOW ROLES;
 
CREATE OR REPLACE MASKING POLICY CONTROL.MASK_ADDRESS AS (VAL VARCHAR) 
RETURNS VARCHAR ->
 CASE 
 WHEN CURRENT_ROLE() IN ('NETWORK_ENGINEER_ROLE','ACCOUNTADMIN','SYSADMIN') 
 THEN VAL ELSE '***MASKED***' END;

-- Applying Policies to our Customers Fact Table:
ALTER TABLE GOLD.DIM_CUSTOMER
MODIFY COLUMN EMAIL SET MASKING POLICY CONTROL.MASK_CONTACT;

ALTER TABLE GOLD.DIM_CUSTOMER 
MODIFY COLUMN PHONE SET MASKING POLICY CONTROL.MASK_CONTACT;

ALTER TABLE GOLD.DIM_CUSTOMER 
MODIFY COLUMN ADDRESS_LINE SET MASKING POLICY CONTROL.MASK_ADDRESS;

