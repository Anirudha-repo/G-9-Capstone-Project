CUSTOMER_ID,
CUSTOMER_NAME,
CUSTOMER_TYPE,
EMAIL,
PHONE,
ADDRESS_LINE,
CITY,
STATE,
REGION,
CUSTOMER_SEGMENT 
FROM GOLD.DIM_CUSTOMER;

