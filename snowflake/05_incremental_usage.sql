-- 4. GOLD FACT REFRESH
-- Gold initial build created MART_USAGE_SUMMARY as a VIEW. Do not replace it
-- with a table. The view will reflect the rebuilt FACT_USAGE automatically.
-- This procedure refreshes only the current SCD2 version of each transaction.
CREATE OR REPLACE PROCEDURE GOLD.SP_REFRESH_USAGE_FACT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
    CREATE OR REPLACE TABLE GOLD.FACT_USAGE AS
    SELECT
        U.USAGE_TRANSACTION_ID,
        U.SUBSCRIPTION_ID,
        U.CUSTOMER_ID,
        U.NETWORK_ELEMENT_ID,
        TO_NUMBER(TO_CHAR(U.USAGE_TS::DATE, 'YYYYMMDD')) AS DATE_KEY,
        U.USAGE_TS,
        U.USAGE_TYPE,
        U.VOICE_MINUTES,
        U.SMS_COUNT,
        U.DATA_VOLUME_MB,
        U.ROAMING_FLAG,
        U.CHARGE_AMOUNT,
        U.DQ_STATUS,
        U.EFFECTIVE_FROM AS USAGE_VERSION_EFFECTIVE_FROM
    FROM SILVER.VW_USAGE_TRANSACTIONS_CURRENT U
    INNER JOIN GOLD.DIM_SUBSCRIPTION S
      ON U.SUBSCRIPTION_ID = S.SUBSCRIPTION_ID
     AND U.CUSTOMER_ID = S.CUSTOMER_ID
    INNER JOIN GOLD.DIM_CUSTOMER C
      ON U.CUSTOMER_ID = C.CUSTOMER_ID
    INNER JOIN GOLD.DIM_NETWORK_ELEMENT N
      ON U.NETWORK_ELEMENT_ID = N.NETWORK_ELEMENT_ID
    INNER JOIN GOLD.DIM_DATE D
      ON TO_NUMBER(TO_CHAR(U.USAGE_TS::DATE, 'YYYYMMDD')) = D.DATE_KEY
    WHERE U.USAGE_TS IS NOT NULL;

    RETURN 'GOLD.FACT_USAGE refreshed from current Silver Usage versions. '
      || 'GOLD.MART_USAGE_SUMMARY remains a view and updates automatically.';
END;
$$;

