
-- TELECOM CAPSTONE: INCREMENTAL USAGE LOAD (BRONZE STREAM -> SILVER SCD TYPE 2 -> GOLD FACT REFRESH)

USE DATABASE TELECOM_DB;
USE WAREHOUSE TELECOM_WH;

-- 1. STREAM
-- Create after initial Bronze ingestion so old rows are not replayed.
CREATE OR REPLACE STREAM BRONZE.USAGE_BRONZE_STREAM
  ON TABLE BRONZE.BRONZE_USAGE_TRANSACTIONS
  APPEND_ONLY = TRUE
  SHOW_INITIAL_ROWS = FALSE;

-- 2. INCREMENTAL SCD TYPE 2 PROCEDURE
CREATE OR REPLACE PROCEDURE CONTROL.SP_PROCESS_USAGE_STREAM()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_STREAM_ROWS NUMBER DEFAULT 0;
    V_VALID_ROWS NUMBER DEFAULT 0;
    V_EXCEPTIONS NUMBER DEFAULT 0;
    V_EXPIRED NUMBER DEFAULT 0;
    V_INSERTED NUMBER DEFAULT 0;
BEGIN
    -- Session-local work table. It is recreated for each procedure execution.
    CREATE OR REPLACE TEMPORARY TABLE TMP_USAGE_STREAM_BATCH (
        USAGE_TRANSACTION_ID VARCHAR,
        SUBSCRIPTION_ID VARCHAR,
        CUSTOMER_ID VARCHAR,
        USAGE_TS TIMESTAMP_TZ,
        USAGE_TYPE VARCHAR,
        VOICE_MINUTES NUMBER(12,2),
        SMS_COUNT NUMBER(18,0),
        DATA_VOLUME_MB NUMBER(18,2),
        ROAMING_FLAG BOOLEAN,
        NETWORK_ELEMENT_ID VARCHAR,
        CHARGE_AMOUNT NUMBER(12,2),
        SOURCE_UPDATED_TS TIMESTAMP_TZ,
        VERSION_TS TIMESTAMP_TZ,
        ROW_HASH NUMBER(38,0),
        SOURCE_FILE VARCHAR,
        LOADED_AT TIMESTAMP_TZ
    );

    BEGIN TRANSACTION;

    -- Read/consume only newly appended stream rows. TRY_ conversions prevent
    -- malformed values from aborting the whole batch.
    INSERT INTO TMP_USAGE_STREAM_BATCH
    SELECT
        NULLIF(TRIM(USAGE_TRANSACTION_ID), ''),
        NULLIF(TRIM(SUBSCRIPTION_ID), ''),
        NULLIF(TRIM(CUSTOMER_ID), ''),
        TRY_TO_TIMESTAMP_TZ(USAGE_TS),
        NULLIF(TRIM(USAGE_TYPE), ''),
        TRY_TO_DECIMAL(VOICE_MINUTES, 12, 2),
        TRY_TO_NUMBER(SMS_COUNT),
        TRY_TO_DECIMAL(DATA_VOLUME_MB, 18, 2),
        CASE
          WHEN UPPER(TRIM(ROAMING_FLAG)) IN ('TRUE','1','Y','YES') THEN TRUE
          WHEN UPPER(TRIM(ROAMING_FLAG)) IN ('FALSE','0','N','NO') THEN FALSE
          ELSE NULL
        END,
        NULLIF(TRIM(NETWORK_ELEMENT_ID), ''),
        TRY_TO_DECIMAL(CHARGE_AMOUNT, 12, 2),
        TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS),
        COALESCE(TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS),
                 TRY_TO_TIMESTAMP_TZ(LOADED_AT::VARCHAR)),
        HASH(
          NULLIF(TRIM(SUBSCRIPTION_ID), ''),
          NULLIF(TRIM(CUSTOMER_ID), ''),
          TRY_TO_TIMESTAMP_TZ(USAGE_TS),
          NULLIF(TRIM(USAGE_TYPE), ''),
          TRY_TO_DECIMAL(VOICE_MINUTES, 12, 2),
          TRY_TO_NUMBER(SMS_COUNT),
          TRY_TO_DECIMAL(DATA_VOLUME_MB, 18, 2),
          CASE
            WHEN UPPER(TRIM(ROAMING_FLAG)) IN ('TRUE','1','Y','YES') THEN TRUE
            WHEN UPPER(TRIM(ROAMING_FLAG)) IN ('FALSE','0','N','NO') THEN FALSE
            ELSE NULL
          END,
          NULLIF(TRIM(NETWORK_ELEMENT_ID), ''),
          TRY_TO_DECIMAL(CHARGE_AMOUNT, 12, 2)
        ),
        SOURCE_FILE,
        TRY_TO_TIMESTAMP_TZ(LOADED_AT::VARCHAR)
    FROM BRONZE.USAGE_BRONZE_STREAM;

    SELECT COUNT(*) INTO :V_STREAM_ROWS FROM TMP_USAGE_STREAM_BATCH;

    -- Log invalid rows and rows with missing Silver parent records.
    INSERT INTO CONTROL.SILVER_EXCEPTIONS
      (ENTITY, BUSINESS_KEY, EXCEPTION_TYPE, REASON, SOURCE_FILE, RAW_RECORD)
    SELECT
      'USAGE_TRANSACTIONS',
      COALESCE(USAGE_TRANSACTION_ID, '<MISSING_USAGE_TRANSACTION_ID>'),
      CASE
        WHEN USAGE_TRANSACTION_ID IS NULL THEN 'MISSING_BUSINESS_KEY'
        WHEN USAGE_TS IS NULL THEN 'INVALID_USAGE_TIMESTAMP'
        WHEN VERSION_TS IS NULL THEN 'INVALID_VERSION_TIMESTAMP'
        WHEN SUBSCRIPTION_ID IS NULL OR CUSTOMER_ID IS NULL
             OR NETWORK_ELEMENT_ID IS NULL THEN 'MISSING_REQUIRED_REFERENCE'
        WHEN VOICE_MINUTES IS NULL AND SMS_COUNT IS NULL
             AND DATA_VOLUME_MB IS NULL AND CHARGE_AMOUNT IS NULL
             THEN 'INVALID_USAGE_MEASURES'
        WHEN NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_CUSTOMERS C
          WHERE C.CUSTOMER_ID = B.CUSTOMER_ID
        ) THEN 'ORPHAN_CUSTOMER'
        WHEN NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S
          WHERE S.SUBSCRIPTION_ID = B.SUBSCRIPTION_ID
            AND S.CUSTOMER_ID = B.CUSTOMER_ID
        ) THEN 'ORPHAN_SUBSCRIPTION'
        WHEN NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N
          WHERE N.NETWORK_ELEMENT_ID = B.NETWORK_ELEMENT_ID
        ) THEN 'ORPHAN_NETWORK_ELEMENT'
      END,
      CASE
        WHEN USAGE_TRANSACTION_ID IS NULL THEN 'USAGE_TRANSACTION_ID is blank.'
        WHEN USAGE_TS IS NULL THEN 'USAGE_TS could not be parsed.'
        WHEN VERSION_TS IS NULL THEN 'Neither SOURCE_UPDATED_TS nor LOADED_AT is a valid timestamp.'
        WHEN SUBSCRIPTION_ID IS NULL OR CUSTOMER_ID IS NULL
             OR NETWORK_ELEMENT_ID IS NULL
             THEN 'One or more required reference keys are blank.'
        WHEN VOICE_MINUTES IS NULL AND SMS_COUNT IS NULL
             AND DATA_VOLUME_MB IS NULL AND CHARGE_AMOUNT IS NULL
             THEN 'All usage measures failed conversion or are NULL.'
        WHEN NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_CUSTOMERS C
          WHERE C.CUSTOMER_ID = B.CUSTOMER_ID
        ) THEN 'CUSTOMER_ID does not exist in Silver customers.'
        WHEN NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S
          WHERE S.SUBSCRIPTION_ID = B.SUBSCRIPTION_ID
            AND S.CUSTOMER_ID = B.CUSTOMER_ID
        ) THEN 'Subscription is missing or does not belong to CUSTOMER_ID.'
        WHEN NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N
          WHERE N.NETWORK_ELEMENT_ID = B.NETWORK_ELEMENT_ID
        ) THEN 'NETWORK_ELEMENT_ID does not exist in Silver network elements.'
      END,
      SOURCE_FILE,
      OBJECT_CONSTRUCT_KEEP_NULL(
        'USAGE_TRANSACTION_ID', USAGE_TRANSACTION_ID,
        'SUBSCRIPTION_ID', SUBSCRIPTION_ID,
        'CUSTOMER_ID', CUSTOMER_ID,
        'USAGE_TS', USAGE_TS,
        'USAGE_TYPE', USAGE_TYPE,
        'VOICE_MINUTES', VOICE_MINUTES,
        'SMS_COUNT', SMS_COUNT,
        'DATA_VOLUME_MB', DATA_VOLUME_MB,
        'ROAMING_FLAG', ROAMING_FLAG,
        'NETWORK_ELEMENT_ID', NETWORK_ELEMENT_ID,
        'CHARGE_AMOUNT', CHARGE_AMOUNT,
        'SOURCE_UPDATED_TS', SOURCE_UPDATED_TS,
        'SOURCE_FILE', SOURCE_FILE
      )
    FROM TMP_USAGE_STREAM_BATCH B
    WHERE USAGE_TRANSACTION_ID IS NULL
       OR USAGE_TS IS NULL
       OR VERSION_TS IS NULL
       OR SUBSCRIPTION_ID IS NULL
       OR CUSTOMER_ID IS NULL
       OR NETWORK_ELEMENT_ID IS NULL
       OR (VOICE_MINUTES IS NULL AND SMS_COUNT IS NULL
           AND DATA_VOLUME_MB IS NULL AND CHARGE_AMOUNT IS NULL)
       OR NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_CUSTOMERS C
          WHERE C.CUSTOMER_ID = B.CUSTOMER_ID
       )
       OR NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S
          WHERE S.SUBSCRIPTION_ID = B.SUBSCRIPTION_ID
            AND S.CUSTOMER_ID = B.CUSTOMER_ID
       )
       OR NOT EXISTS (
          SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N
          WHERE N.NETWORK_ELEMENT_ID = B.NETWORK_ELEMENT_ID
       );

    V_EXCEPTIONS := SQLROWCOUNT;

    -- Build one latest incoming candidate per transaction ID. Validity is
    -- checked again in the source CTE used by the SCD2 operations.
    CREATE OR REPLACE TEMPORARY TABLE TMP_USAGE_VALID_LATEST AS
    SELECT *
    FROM TMP_USAGE_STREAM_BATCH B
    WHERE B.USAGE_TRANSACTION_ID IS NOT NULL
      AND B.USAGE_TS IS NOT NULL
      AND B.VERSION_TS IS NOT NULL
      AND B.SUBSCRIPTION_ID IS NOT NULL
      AND B.CUSTOMER_ID IS NOT NULL
      AND B.NETWORK_ELEMENT_ID IS NOT NULL
      AND NOT (B.VOICE_MINUTES IS NULL AND B.SMS_COUNT IS NULL
               AND B.DATA_VOLUME_MB IS NULL AND B.CHARGE_AMOUNT IS NULL)
      AND EXISTS (
        SELECT 1 FROM SILVER.SILVER_CUSTOMERS C
        WHERE C.CUSTOMER_ID = B.CUSTOMER_ID
      )
      AND EXISTS (
        SELECT 1 FROM SILVER.SILVER_SUBSCRIPTIONS S
        WHERE S.SUBSCRIPTION_ID = B.SUBSCRIPTION_ID
          AND S.CUSTOMER_ID = B.CUSTOMER_ID
      )
      AND EXISTS (
        SELECT 1 FROM SILVER.SILVER_NETWORK_ELEMENTS N
        WHERE N.NETWORK_ELEMENT_ID = B.NETWORK_ELEMENT_ID
      )
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY B.USAGE_TRANSACTION_ID
      ORDER BY B.VERSION_TS DESC, B.LOADED_AT DESC
    ) = 1;

    SELECT COUNT(*) INTO :V_VALID_ROWS FROM TMP_USAGE_VALID_LATEST;

    -- 2A. Close current version when a newer, changed version arrives.
    UPDATE SILVER.SILVER_USAGE_TRANSACTIONS T
       SET EFFECTIVE_TO = S.VERSION_TS,
           IS_CURRENT = FALSE,
           PROCESSED_AT = CURRENT_TIMESTAMP()
      FROM TMP_USAGE_VALID_LATEST S
     WHERE T.USAGE_TRANSACTION_ID = S.USAGE_TRANSACTION_ID
       AND T.IS_CURRENT = TRUE
       AND S.VERSION_TS > T.EFFECTIVE_FROM
       AND HASH(
         T.SUBSCRIPTION_ID, T.CUSTOMER_ID, T.USAGE_TS, T.USAGE_TYPE,
         T.VOICE_MINUTES, T.SMS_COUNT, T.DATA_VOLUME_MB, T.ROAMING_FLAG,
         T.NETWORK_ELEMENT_ID, T.CHARGE_AMOUNT
       ) <> S.ROW_HASH;

    V_EXPIRED := SQLROWCOUNT;

    -- 2B. If the payload is unchanged but its source timestamp is newer,
    -- update only source metadata. Do not create a needless SCD2 version.
    UPDATE SILVER.SILVER_USAGE_TRANSACTIONS T
       SET SOURCE_UPDATED_TS = S.SOURCE_UPDATED_TS,
           SOURCE_FILE = S.SOURCE_FILE,
           PROCESSED_AT = CURRENT_TIMESTAMP()
      FROM TMP_USAGE_VALID_LATEST S
     WHERE T.USAGE_TRANSACTION_ID = S.USAGE_TRANSACTION_ID
       AND T.IS_CURRENT = TRUE
       AND S.VERSION_TS > T.EFFECTIVE_FROM
       AND HASH(
         T.SUBSCRIPTION_ID, T.CUSTOMER_ID, T.USAGE_TS, T.USAGE_TYPE,
         T.VOICE_MINUTES, T.SMS_COUNT, T.DATA_VOLUME_MB, T.ROAMING_FLAG,
         T.NETWORK_ELEMENT_ID, T.CHARGE_AMOUNT
       ) = S.ROW_HASH;

    -- 2C. Insert new transaction IDs and the changed versions whose old
    -- current row was just closed. Also handles an empty initial Silver table.
    INSERT INTO SILVER.SILVER_USAGE_TRANSACTIONS
      (USAGE_TRANSACTION_ID, SUBSCRIPTION_ID, CUSTOMER_ID, USAGE_TS,
       USAGE_TYPE, VOICE_MINUTES, SMS_COUNT, DATA_VOLUME_MB, ROAMING_FLAG,
       NETWORK_ELEMENT_ID, CHARGE_AMOUNT, SOURCE_UPDATED_TS,
       EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT, DQ_STATUS, SOURCE_FILE,
       PROCESSED_AT)
    SELECT
       S.USAGE_TRANSACTION_ID, S.SUBSCRIPTION_ID, S.CUSTOMER_ID, S.USAGE_TS,
       S.USAGE_TYPE, S.VOICE_MINUTES, S.SMS_COUNT, S.DATA_VOLUME_MB,
       S.ROAMING_FLAG, S.NETWORK_ELEMENT_ID, S.CHARGE_AMOUNT,
       S.SOURCE_UPDATED_TS, S.VERSION_TS, NULL, TRUE,
       IFF(S.DATA_VOLUME_MB = 1000000, 'OUTLIER', 'IDMC_CLEAN'),
       S.SOURCE_FILE, CURRENT_TIMESTAMP()
    FROM TMP_USAGE_VALID_LATEST S
    WHERE NOT EXISTS (
      SELECT 1
      FROM SILVER.SILVER_USAGE_TRANSACTIONS T
      WHERE T.USAGE_TRANSACTION_ID = S.USAGE_TRANSACTION_ID
        AND T.IS_CURRENT = TRUE
    );

    V_INSERTED := SQLROWCOUNT;

    COMMIT;

    RETURN 'Stream rows=' || V_STREAM_ROWS
      || '; valid latest candidates=' || V_VALID_ROWS
      || '; exception rows logged=' || V_EXCEPTIONS
      || '; previous versions expired=' || V_EXPIRED
      || '; new current versions inserted=' || V_INSERTED;

EXCEPTION
    WHEN OTHER THEN
      ROLLBACK;
      RAISE;
END;
$$;

-- 3. TASK
-- Task calls the procedure only when the stream has data.
CREATE OR REPLACE TASK CONTROL.TASK_MERGE_USAGE
  WAREHOUSE = TELECOM_WH
  SCHEDULE = '5 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('TELECOM_DB.BRONZE.USAGE_BRONZE_STREAM')
AS
  CALL CONTROL.SP_PROCESS_USAGE_STREAM();

