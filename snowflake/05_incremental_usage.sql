-- 5. POST-LOAD VALIDATION
-- Expected: no transaction should have more than one current version.
SELECT USAGE_TRANSACTION_ID, COUNT_IF(IS_CURRENT = TRUE) AS CURRENT_VERSION_COUNT
FROM SILVER.SILVER_USAGE_TRANSACTIONS
GROUP BY USAGE_TRANSACTION_ID
HAVING COUNT_IF(IS_CURRENT = TRUE) > 1;

-- Expected: no transaction should have zero current versions.
SELECT USAGE_TRANSACTION_ID
FROM SILVER.SILVER_USAGE_TRANSACTIONS
GROUP BY USAGE_TRANSACTION_ID
HAVING COUNT_IF(IS_CURRENT = TRUE) = 0;

-- Current Silver count compared with Gold fact count. Differences can occur
-- if a current usage row has invalid/missing Gold dimension/date relationships.
SELECT
  (SELECT COUNT(*) FROM SILVER.VW_USAGE_TRANSACTIONS_CURRENT) AS SILVER_CURRENT_ROWS,
  (SELECT COUNT(*) FROM GOLD.FACT_USAGE) AS GOLD_FACT_ROWS;

-- Mart is a view. Confirm its object type and current results.
SHOW VIEWS LIKE 'MART_USAGE_SUMMARY' IN SCHEMA GOLD;
SELECT * FROM GOLD.MART_USAGE_SUMMARY ORDER BY USAGE_DATE DESC LIMIT 50;

